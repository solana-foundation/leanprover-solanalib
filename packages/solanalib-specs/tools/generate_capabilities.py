#!/usr/bin/env python3
"""Generate typed capability catalogs from the existing source registry.

Run from any directory; --check verifies generated bytes without writing.
The Lean/source audit separately checks the selected declaration identities.
No model contract, source pin or registry entry is synthesized here. The Rust identities of each member come from `rust_identities` in the source-map loader.
"""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import sys


PACKAGE = Path(__file__).resolve().parents[1]
REPO = PACKAGE.parents[1]
sys.path.insert(0, str(REPO / "tools" / "model-audit"))
from solana_specs_config import module_root
from lean_format import format_source, HEADER, code_only
from solana_source_map import load_source_map, rust_identities  # noqa: E402
from solana_applicability import lean_profile, normalized_applicability  # noqa: E402


def declaration_modules(roots):
    """Locate the explicit declarations already required by the registry.

    This scan chooses imports, never verifies the Lean type of a declaration. Missing
    or ambiguous public declarations fail instead of guessing an aggregate.
    """
    found = defaultdict(set)
    for path in sorted(PACKAGE.rglob("*.lean")):
        relative = path.relative_to(PACKAGE)
        if module_root(".".join(relative.with_suffix("").parts)) not in roots:
            continue
        stack = []
        commands = re.compile(
            r"^namespace\s+(?P<namespace>[^\s]+)|"
            r"^(?:public\s+|private\s+)?(?P<section>section)(?:[ \t]+[^\n]*)?$|"
            r"^(?P<end>end)(?:[ \t]+[^\n]*)?$|"
            r"^(?:(?:public|protected|noncomputable)\s+)*"
            r"(?:def|abbrev|theorem|opaque|structure|inductive)\s+(?P<declaration>[^\s:(]+)", re.M)
        for command in commands.finditer(code_only(path.read_text())):
            if command["namespace"]:
                stack.append(("namespace", command["namespace"]))
            elif command["section"]:
                stack.append(("section", ""))
            elif command["end"]:
                if stack:
                    stack.pop()
            else:
                prefix = ".".join(name for kind, name in stack if kind == "namespace")
                name = (prefix + "." if prefix else "") + command["declaration"]
                found[name].add(relative.with_suffix("").as_posix().replace("/", "."))
    return found


def key_name(model):
    path = model["contract"][len(module_root(model["contract"])) + 1:].removesuffix("_contract")
    return re.sub(r"[^A-Za-z0-9_]", "_", path)


def reference_term(model):
    reference = model["reference"]
    if isinstance(reference, str):
        return reference
    return f"({reference['projection']} {reference['receiver']})"


def lean_string(text):
    """A Lean string literal; control characters are rejected, not escaped."""
    if any(ord(character) < 0x20 or ord(character) == 0x7F for character in text):
        raise ValueError(f"Control character in a catalog string: {text!r}")
    return json.dumps(text, ensure_ascii=False)


def identity_term(identity):
    fields = (identity[name] for name in ("crate_name", "crate_version", "item", "implementation"))
    return "⟨" + ", ".join(lean_string(field) for field in fields) + "⟩"


def render(root, models, declarations, identities, applicability=None):
    imports = {"Solanalib.Specs.Core.Capabilities"}
    for model in models:
        reference = model["reference"]
        names = [model["contract"], *model["witnesses"]]
        names.append(reference if isinstance(reference, str) else reference["receiver"])
        if model.get("family"):
            names.append(model["family"])
        for name in names:
            candidates = declarations.get(name, set())
            if len(candidates) != 1:
                raise ValueError(f"Expected one source module for {name}: {sorted(candidates)}")
            imports.update(candidates)
    keys = [key_name(model) for model in models]
    if len(keys) != len(set(keys)):
        raise ValueError(f"Repeated capability member in {root}")
    namespace = ("Solanalib.Specs.Core.SupportingCapabilities" if root == "Solanalib.Specs.Core"
                 else root + ".Capabilities")
    lines = ["module", "", "-- Generated by tools/generate_capabilities.py; do not edit by hand.", ""]
    lines += ["public import " + name for name in sorted(imports)]
    lines += ["", "@[expose] public section", "", "set_option autoImplicit false", "",
              "namespace " + namespace, "", "open Solanalib.Contracts.Model Solanalib.Specs", "",
              "/-- The exact registered model members; roles remain explicit in `catalog`. -/",
              "inductive Key where"]
    for model, key in zip(models, keys):
        lines += [f"  /-- `{model['contract'].removeprefix(root + '.')}`. -/", "  | " + key]
    lines += ["  deriving DecidableEq, Repr", "",
              "/-- Every registered family at its original indices; nongeneric contracts",
              "use the singleton embedding without changing their predicate. -/",
              "def catalog : Solanalib.Contracts.Model.Capabilities.Catalog where", "  Key := Key",
              "  family := fun key => match key with"]
    for model, key in zip(models, keys):
        family = (model.get("family", model["contract"])
                  if model["witness_kind"] == "FamilyReference"
                  else "Solanalib.Contracts.Model.Capabilities.single " + model["contract"])
        lines.append(f"    | .{key} => {family}")
    lines += ["  modelId := fun key => match key with"]
    for model, key in zip(models, keys):
        lines.append(f"    | .{key} => {lean_string(model['id'])}")
    lines += ["  kind := fun key => match key with"]
    for model, key in zip(models, keys):
        kind = "partialModel" if model["kind"] == "partial" else model["kind"]
        lines.append(f"    | .{key} => .{kind}")
    lines += ["  identities := fun key => match key with"]
    for model, key in zip(models, keys):
        terms = ", ".join(identity_term(identity) for identity in identities.get(model["id"], []))
        lines.append(f"    | .{key} => [{terms}]")
    if applicability is not None:
        lines += ["  applicability := fun key => match key with"]
        for model, key in zip(models, keys):
            profiles = applicability[model["id"]]["profiles"]
            if profiles:
                terms = ",\n".join(
                    "      " + lean_profile(profile, multiline=True, review=False).replace("\n", "\n      ")
                    for profile in profiles)
                lines.append(f"    | .{key} => [\n{terms}\n    ]")
            else:
                lines.append(f"    | .{key} => []")
        lines += ["  applicabilityConsumers := fun key => match key with"]
        for model, key in zip(models, keys):
            consumers = ", ".join(lean_string(name) for name in applicability[model["id"]]["consumers"])
            lines.append(f"    | .{key} => [{consumers}]")
    lines += ["", "/-- The selected members and generic instantiations required by a client. -/",
              "abbrev Selection := Solanalib.Contracts.Model.Capabilities.Selection catalog", "",
              "/-- One fixed assignment of the supplied outcome relations. -/",
              "abbrev Operations := Solanalib.Contracts.Model.Capabilities.Operations catalog", "",
              "/-- Explicit propositional assumptions on just the requested operations. -/",
              "abbrev Spec (needs : Selection) (operations : Operations) : Prop :=",
              "  Solanalib.Contracts.Model.Capabilities.Spec catalog needs operations", "",
              "/-- The existing mathematical references, with no Rust correctness claim. -/",
              "def reference : Operations := fun key => match key with"]
    for model, key in zip(models, keys):
        term = reference_term(model)
        if model["witness_kind"] == "RealizedBy":
            term = "fun _ => returnsOf " + term
        elif model["witness_kind"] == "Holds":
            term = "fun _ => " + term
        lines.append(f"  | .{key} => {term}")
    lines += ["", "/-- Existing closed reference theorems establish the entire mathematical",
              "bundle at every generic index. They do not discharge source-call assumptions. -/",
              "theorem reference_spec :",
              "    Spec (Solanalib.Contracts.Model.Capabilities.Selection.all catalog) reference := by",
              "  constructor", "  intro key index _", "  cases key with"]
    for model, key in zip(models, keys):
        witness = model["witnesses"][0]
        if model["witness_kind"] == "RealizedBy":
            term = f"(Solanalib.Contracts.Model.realized_iff_holds _ _).mp {witness}"
        elif model["witness_kind"] == "FamilyReference":
            term = witness + " index"
        else:
            term = witness
        lines.append(f"  | {key} => exact {term}")
    lines += ["", "end " + namespace, ""]
    path = PACKAGE / (namespace.replace(".", "/") + ".lean")
    # Shorten code references only; registry strings are observable metadata.
    # Explicit alternatives keep tactic/term continuation columns stable.
    laid_out = []
    for line in lines:
        match = re.match(r"^( +\| [^\n]*? =>) (.*)$", line)
        if match and len(line) > 100:
            indent = len(line) - len(line.lstrip())
            laid_out.extend((match[1], " " * (indent + 2) + match[2]))
        else:
            laid_out.append(line)
    text = "\n".join(laid_out)
    mask = code_only(text)
    replacements = []
    for match in re.finditer(r"Solanalib\.Specs\.([A-Z][A-Za-z0-9]*\.[A-Za-z0-9_'.]+)", mask):
        before = mask[mask.rfind("\n", 0, match.start()) + 1:match.start()]
        if before in {"public import ", "namespace ", "end "}:
            continue
        replacements.append((match.start(), match.end(),
                             match[0][len(root) + 1:] if match[0].startswith(root + ".") else match[1]))
    for start, end, value in reversed(replacements):
        text = text[:start] + value + text[end:]
    return path, format_source(HEADER + text)



def generated_files():
    source_map = load_source_map(PACKAGE)
    models = source_map["models"]
    identities = rust_identities(source_map)
    applicability = ({row["model_id"]: row for row in normalized_applicability(source_map)["models"]}
                     if "applicability" in source_map else None)
    grouped = defaultdict(list)
    for model in models:
        grouped[module_root(model["contract"])].append(model)
    declarations = declaration_modules(set(grouped))
    return [render(root, sorted(group, key=lambda model: model["id"]), declarations, identities, applicability)
            for root, group in sorted(grouped.items())]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatches = []
    files = generated_files()
    for path, contents in files:
        if path.exists() and path.read_text() == contents:
            continue
        if args.check:
            mismatches.append(str(path.relative_to(PACKAGE)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    if mismatches:
        raise SystemExit("Stale capability catalogs: " + ", ".join(mismatches))
    print(f"{'Checked' if args.check else 'Generated'} {len(files)} capability catalogs from the source registry")


if __name__ == "__main__":
    main()
