"""Generate the complete scenario, checker and native-driver index."""
import argparse
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'docs/tests.md'


def link(path):
    relative = path.relative_to(ROOT).as_posix()
    return f'[{relative}](../{relative})'


def lean_modules(base):
    return sorted([*base.glob('SolanalibTest.lean'), *(base / 'SolanalibTest').rglob('*.lean')])


def render():
    sections = [
        ('Root regression tests', 'just test', lean_modules(ROOT)),
        ('Worked example', 'just test-examples', lean_modules(ROOT / 'examples')),
        ('Runtime scenarios', 'just test-runtime', lean_modules(ROOT / 'packages/solanalib-runtime')),
        ('SDK scenarios', 'just test-specs', lean_modules(ROOT / 'packages/solanalib-specs')),
        ('Runtime replay harness', 'just test-conformance', lean_modules(ROOT / 'tools/runtime-conformance')),
        ('SDK checkers and replay harness', 'just test-conformance', lean_modules(ROOT / 'tools/library-conformance')),
    ]
    lines = ['# Test and checker index', '',
             'Generated by `python3.12 scripts/generate-test-index.py`; CI checks it with `--check`. '
             'Every Lean scenario, example, checker and test aggregator under the listed source roots is linked below. '
             'Aggregators and harness helpers are included for navigation; file counts are not coverage claims.', '',
             'Run commands from the repository root after [setup](getting-started.md). '
             '`just check-all` runs all regular suites, including proof/source audits, replay controls and documentation. '
             'Fresh native reproduction uses the separate `test-native-runtime` and `test-native-library` recipes. '
             'The [gap index](model-gaps.md) records omissions and unproved connections.', '',
             '| Suite | Command | Indexed Lean files |', '| --- | --- | --- |']
    for title, command, paths in sections:
        lines.append(f'| {title} | `{command}` | {len(paths)} |')
    for title, command, paths in sections:
        if not paths:
            raise ValueError('Empty test source root: ' + title)
        lines += ['', '## ' + title, '', f'Command: `{command}`.', '']
        lines.extend('- ' + link(path) for path in paths)
    lines += ['', '## Python controls', '',
              'These suites test generators, source/identity checks, proof audits and native-recording authentication. '
              '`audit` enables compiled SDK counterexamples; `test-conformance` enables actual Lean selection controls.', '',
              '| Test file | Recipe |', '| --- | --- |']
    suites = [('scripts', 'audit'), ('tools/model-audit', 'audit'),
              ('tools/runtime-conformance', 'test-runtime'), ('tools/library-conformance', 'test-conformance')]
    for directory, recipe in suites:
        for path in sorted((ROOT / directory).glob('test_*.py')):
            lines.append(f'| {link(path)} | `just {recipe}` |')
    lines += ['', '## Native drivers and recordings', '',
              'The runtime suite uses [agave_cases.rs](../tools/runtime-conformance/agave_cases.rs), '
              '[cpi_cases.rs](../tools/runtime-conformance/cpi_cases.rs), shared '
              '[account](../tools/runtime-conformance/accounts.tsv), '
              '[serialization](../tools/runtime-conformance/serialization.tsv) and '
              '[CPI](../tools/runtime-conformance/cpi.tsv) fixtures, and the authenticated '
              '[recording metadata](../tools/runtime-conformance/expected-native.json). '
              'See its [native reproduction guide](../tools/runtime-conformance/README.md#reproduce-native-results) for the sealed Agave archive and compiler.', '',
              'Every SDK driver discovered from `driver.toml` is listed with all corpora it owns. '
              'Use `just test-native-library DRIVER EVIDENCE` with a fresh evidence directory for native observations without changing committed recordings. '
              'A [driver manifest](../tools/library-conformance/REFERENCE.md#families) also identifies shared source inputs, source/build scope and lockfiles. '
              'Checker registration and recorded omissions remain authoritative for replay coverage.', '',
              '| Driver and source directory | Complete corpora |', '| --- | --- |']
    for path in sorted((ROOT / 'tools/library-conformance/rust').glob('*/driver.toml')):
        data = tomllib.loads(path.read_text())
        corpora = [ROOT / 'tools/library-conformance/corpus' / (name + '.json') for name in data['corpora']]
        if not all(corpus.is_file() for corpus in corpora):
            raise ValueError('Missing recorded corpus for ' + str(path))
        lines.append(f'| {link(path)} | ' + ', '.join(link(corpus) for corpus in corpora) + ' |')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            raise SystemExit('Stale test index: run python3.12 scripts/generate-test-index.py')
    else:
        OUTPUT.write_text(expected)
    print('Test index: complete scenarios, checker modules, Python controls and native drivers')


if __name__ == '__main__':
    main()
