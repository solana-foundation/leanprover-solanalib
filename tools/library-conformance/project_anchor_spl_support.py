#!/usr/bin/env python3
"""Project sealed Anchor SPL wrapper items at an opaque invocation signature.

Only the selected function item is copied. Context/account types and all
constructors are the real exact-version dependencies. No invocation body is
read, copied or run. --check rejects drift in the source items or projection.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PROFILES = {
    "v027": ("0.27.0", {"stake": ["withdraw", "deactivate_stake"]}),
    "v029": ("0.29.0", {}),
    "v0321-pubkey221": ("0.32.1", {"associated_token": ["create"], "memo": ["build_memo"], "metadata": ["create_metadata_accounts_v3"]}),
    "v0321-pubkey240": ("0.32.1", {"associated_token": ["create"], "metadata": ["create_metadata_accounts_v3"]}),
    "v0321-interface": ("0.32.1", {}),
    "v102": ("1.0.2", {"associated_token": ["create_idempotent"]}),
    "v112": ("1.1.2", {"associated_token": ["create", "create_idempotent"]}),
}
IMPORTS = {
    "stake": "use anchor_lang::{context::CpiContext, Result};\nuse anchor_lang::solana_program::{account_info::AccountInfo, stake};\nuse anchor_spl::stake::{Withdraw, DeactivateStake};\n",
    "associated_token": "use anchor_lang::{context::CpiContext, Result};\nuse anchor_spl::associated_token::{Create, spl_associated_token_account};\ntype CreateIdempotent<'info> = Create<'info>;\n",
    "memo": "use anchor_lang::{context::CpiContext, Result};\nuse anchor_spl::memo::{BuildMemo, spl_memo};\n",
    "metadata": "use anchor_lang::{context::CpiContext, Result, ToAccountInfos};\nuse anchor_lang::system_program;\nuse anchor_spl::metadata::{CreateMetadataAccountsV3, mpl_token_metadata};\n",
}

def item(source, name):
    start = source.index("pub fn " + name + "<")
    opening = source.index("{", start)
    depth = 1
    cursor = opening + 1
    while depth:
        if source[cursor] == "{": depth += 1
        if source[cursor] == "}": depth -= 1
        cursor += 1
    return source[start:cursor]

def sha(data): return hashlib.sha256(data).hexdigest()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for profile, (version, modules) in PROFILES.items():
        source_root = args.registry / ("anchor-spl-" + version) / "src"
        records = []
        contents = ["// Generated by project_anchor_spl_support.py; do not edit.\n// Exact selected SDK wrapper items; only the invocation signature is mocked.\n"]
        for module, names in modules.items():
            file = source_root / (module + ".rs")
            raw = file.read_bytes()
            bodies = []
            for name in names:
                selected = item(raw.decode(), name)
                if "anchor_lang::solana_program::program::invoke_signed" in selected:
                    callee = "anchor_lang::solana_program::program::invoke_signed"
                else:
                    callee = "solana_program::program::invoke_signed"
                assert selected.count(callee) == 1, (profile, name)
                projected = selected.replace(callee, "crate::whole_signature::invoke_signed")
                records.append({"crate": "anchor-spl", "version": version, "path": "src/" + module + ".rs",
                    "file_sha256": sha(raw), "selector": "pub fn " + name,
                    "item_sha256": sha(selected.encode()), "callee": callee,
                    "replacement": "crate::whole_signature::invoke_signed", "replacement_count": 1,
                    "projected_item_sha256": sha(projected.encode())})
                bodies.append(projected)
            contents += ["mod projected_" + module + " {\n" + IMPORTS[module] + "\n\n".join(bodies) + "\n}\n"]
        generated = "\n".join(contents).encode()
        folder = ROOT / "rust" / ("anchor-spl-support-" + profile)
        if not args.check:
            folder.mkdir(parents=True, exist_ok=True)
            (folder / "src").mkdir(exist_ok=True)
        seal = (json.dumps({"scope": "projected-wrapper conformance; the whole invocation is a typed mock",
            "profile": profile, "items": records, "projection_sha256": sha(generated)}, indent=2) + "\n").encode()
        for path, value in [(folder / "src" / "projected.rs", generated), (folder / "projection.json", seal)]:
            if args.check:
                assert path.read_bytes() == value, "stale projection: " + str(path)
            else:
                path.write_bytes(value)
    print("Anchor SPL support projections verified" if args.check else "Anchor SPL support projections written")

if __name__ == "__main__": main()
