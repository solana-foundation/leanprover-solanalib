# Kernel-checked negative theorems for preconditions no parseable record can break
# (`requires-theorems.toml`): each shows that the decider of the checker rejects an input outside the
# precondition. The audit requires the theorem to exist, to be a theorem, and to use the
# precondition decision of the checker: a declaration of its code that mentions `requires`
# directly (a decider, an iff lemma),
# or a family declaration or a `Decidable` instance that decision is built from.
#
#     [[theorem]]
#     model = "spl-token-2022::onchain::invoke_transfer_checked_value"
#     theorem = "SolanalibTest.Conformance.Library.Families.TokenInterface.Onchain.illTyped_not_ready"
#     detail = "TokenInterface"
