def record(args: argparse.Namespace) -> None:
    evidence = args.evidence_dir.resolve()
    runner = Runner(evidence, args.timeout)
    drivers = discover_drivers()
    selected = args.driver or sorted(drivers)
    unknown = set(selected) - set(drivers)
    require(not unknown, f"unknown drivers {sorted(unknown)}; known: {sorted(drivers)}")
    target_root = (args.target_dir or evidence / "target").resolve()
    toolchain = tomllib.loads((ROOT / "rust-toolchain.toml").read_text())["toolchain"]["channel"]
    overrides = toolchain_overrides()
    require(not overrides, f"toolchain overrides under rust/ are not allowed: {overrides}")
    # The compiler this suite pins, run outside every driver directory.
    _, pinned = runner.run("rustc-version-pinned", ["rustc", "-vV"], ROOT)
    problem = toolchain_problem(pinned.strip().splitlines(), toolchain)
    require(problem is None, f"the rustc of the suite does not match {toolchain}: {problem}")
    offline = ["--offline"] if args.offline else []
    # The controls of the shared crates first: the syscall semantics of the shim and the region layout.
    for crate in ("shim", "accounts"):
        runner.run(f"selftest-{crate}", ["cargo", "test", *offline, "--", "--test-threads=1"], RUST / crate,
                   {"CARGO_TARGET_DIR": str(target_root / f"selftest-{crate}")})
        (RUST / crate / "Cargo.lock").unlink(missing_ok=True)
    workspaces = {native_dependencies.workspace(RUST / driver) for driver in selected}
    modeled = native_dependencies.modeled_crates()
    resolutions = {directory: native_dependencies.fresh_resolution(directory, runner, args.offline, modeled)
                   for directory in sorted(workspaces)}
    total = 0
    for driver in selected:
        cwd = RUST / driver
        _, rustc = runner.run(f"rustc-version-{driver}", ["rustc", "-vV"], cwd)
        require(rustc.strip() == pinned.strip(),
                f"{driver}: rustc in the driver directory differs from the pinned rustc of the suite:\n{rustc}")
        _, cargo = runner.run(f"cargo-version-{driver}", ["cargo", "-V"], cwd)
        out = Path(tempfile.mkdtemp(prefix=f"corpus-{driver}-", dir=evidence))
        config = tomllib.loads((cwd / ".cargo/config.toml").read_text())
        rustflags = config.get("target", {}).get(TARGET, {}).get("rustflags")
        expected_flags = [] if drivers[driver]["host"] else SOLANA_RUSTFLAGS
        require(rustflags == expected_flags,
                f"{driver}: .cargo/config.toml rustflags {rustflags} must be {expected_flags}"
                + ("" if drivers[driver]["host"] else " (or set host = true in driver.toml)"))
        flags = ["--locked"] + (["--offline"] if args.offline else [])
        probe = drivers[driver]["build_probe"]
        flags += ['--profile', drivers[driver]['profile']]
        directory = native_dependencies.workspace(cwd)
        env = {"CARGO_TARGET_DIR": str(target_root / directory.name)}
        _, unit_output = runner.run(f'compiler-units-{driver}',
            ['cargo', 'build', *flags, '--target', TARGET, '--unit-graph', '-Z', 'unstable-options'],
            cwd, env, stdout_only=True)
        resolution, compiled_profile = native_dependencies.compiled_resolution(
            cwd, resolutions[directory], json.loads(unit_output), modeled)
        native_dependencies.validate_resolution(cwd, resolution, native_dependencies.reviewed_checksums())
        require(compiled_profile == native_dependencies.profile(cwd, drivers[driver]['profile']),
                f'{driver}: compiled profile differs from the selected workspace settings')
        runner.run(f"build-{driver}", ["cargo", "build", *flags, "--target", TARGET], cwd, env)
        observed = None
        if probe is not None:
            _, output = runner.run(f"build-probe-{driver}",
                ["cargo", "run", *flags, "-q", "--target", TARGET, "--", probe["argument"]], cwd, env,
                stdout_only=True)
            observed = json.loads(output)
            build_probe.validate(probe, observed, drivers[driver]["host"], driver)
        runner.run(f"record-{driver}", ["cargo", "run", *flags, "-q", "--target", TARGET, "--", str(out)], cwd, env)
        if args.twice:
            again = Path(tempfile.mkdtemp(prefix=f"again-{driver}-", dir=evidence))
            runner.run(f"record-{driver}-again", ["cargo", "run", *flags, "-q", "--target", TARGET, "--", str(again)],
                       cwd, env)
            differing = [p.name for p in sorted(out.glob("*.json")) if p.read_bytes() != (again / p.name).read_bytes()]
            require(not differing, f"driver {driver} is not deterministic: {differing} differ between two runs")
        written = sorted(p.name for p in out.glob("*.json"))
        expected = sorted(f"{c}.json" for c in drivers[driver]["corpora"])
        require(written == expected, f"driver {driver} wrote {written}, its driver.toml lists {expected}")
        corpora = {}
        for name in written:
            summary = validate_corpus(out / name)
            corpora[name] = {"sha256": sha256(out / name), "records": summary["records"], "crates": summary["crates"]}
            total += summary["records"]
        manifest = {
            "schema": MANIFEST_SCHEMA,
            "driver": driver,
            "recorded_utc": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
            "rust": {"toolchain": toolchain, "rustc": rustc.strip().splitlines(), "cargo": cargo.strip(),
                     "target": TARGET, **compiled_profile},
            "inputs": input_hashes(driver, ROOT, drivers),
            "resolution": resolution,
            "rustflags": config["target"][TARGET]["rustflags"],
            "corpora": corpora,
        }
        build_probe.attach(manifest, probe, observed)
        if args.write_corpus:
            (CORPUS / "manifests").mkdir(parents=True, exist_ok=True)
            for name in written:
                shutil.copyfile(out / name, CORPUS / name)
            write_json(CORPUS / "manifests" / f"{driver}.json", manifest)
        else:
            write_json(out / f"{driver}.manifest.json", manifest)
        print(f"Recorded {sum(c['records'] for c in corpora.values())} records for driver {driver}: "
              + ", ".join(written) + ("" if args.write_corpus else f" (in {out})"))
    write_json(evidence / "run-status.json", {
        "status": "passed", "mode": "record", "drivers": selected, "records": total,
        "finished_utc": datetime.now(timezone.utc).isoformat()})


