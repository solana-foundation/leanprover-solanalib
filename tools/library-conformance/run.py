def source_map(directory: Path | None = None) -> dict:
    """The registered models of packages/solanalib-specs/source-map: id -> its constant names (contract,
    reference, family, sample, the receiver of an observation, and the `_run` of a `_contract`), the
    projection of the reference of an observation, its contract and the Rust items it binds
    (`api.rust_names`)."""
    models, entries = {}, []
    for path in sorted((directory or REPO / "packages/solanalib-specs/source-map").glob("*.json")):
        data = json.loads(path.read_text())
        api = data.get("api", {})
        for key, model in data.get("models", {}).items():
            require(key not in models, f"model {key} is registered twice in the source map")
            names = {model[k] for k in ("contract", "reference", "family", "sample") if isinstance(model.get(k), str)}
            reference = model.get("reference")
            receiver = projection = None
            if isinstance(reference, dict):   # the reference of an observation: receiver.projection
                receiver, projection = reference.get("receiver"), reference.get("projection")
                if isinstance(receiver, str):
                    names.add(receiver)
            # A family or relation contract `P_contract` is witnessed against its run `P_run`
            # (`P_reference : FamilyReference P_contract P_run`, checked by the specs audit).
            contract = model.get("contract") if isinstance(model.get("contract"), str) else None
            if contract and contract.endswith("_contract"):
                names.add(contract[: -len("_contract")] + "_run")
            models[key] = {"names": names, "contract": contract, "receiver": receiver, "projection": projection,
                           "rust_names": set()}
        entries += list(api.items())
    # An api entry binds Rust items to the models it lists (`models`), else to the model of its own key.
    for key, entry in entries:
        for model in entry.get("models") or [key]:
            if model in models:
                models[model]["rust_names"] |= set(entry.get("rust_names") or [])
    return models


def registered_constants(models: dict | None = None) -> set[str]:
    """Every registered constant name of the models of the source map."""
    return set().union(*(m["names"] for m in (source_map() if models is None else models).values()))


def decides_problems(lines: list[list[str]], models: dict, requires: dict | None = None,
                     allow: set | None = None) -> dict:
    """Check the per-checker declarations in audit `lines` (DECIDES, REACHES, PRECONDITION).

    Returns `problems`, `covered` (model -> the checkers deciding it), `declared` (names per family)
    and `preconditions` (model -> the checkers deciding its precondition). A declared name decides the
    model it identifies: a name of exactly one model, or the receiver of an observation whose
    projection the code of the checker uses. `requires` maps a contract to the classification of the audit of
    its precondition (`trivial`, `nontrivial`, ...)."""
    requires = requires or {}
    allow = allow if allow is not None else set()
    owners = {}
    for model, info in models.items():
        for name in info["names"]:
            owners.setdefault(name, set()).add(model)
    checkers, reached, claimed, bridges, generics, decidables = {}, {}, {}, {}, {}, {}
    for line in lines:
        if line[0] == "DECIDES":
            _, family, corpus, key, function, name, in_env, in_code = line
            entry = checkers.setdefault((family, corpus, key), {"function": function, "declared": []})
            if name != "-":
                entry["declared"].append((name, in_env, in_code))
        elif line[0] == "REACHES":
            _, family, corpus, key, name = line
            reached.setdefault((family, corpus, key), set()).add(name)
        elif line[0] == "PRECONDITION":
            _, family, corpus, key, name = line
            claimed.setdefault((family, corpus, key), []).append(name)
        elif line[0] == "BRIDGE":
            _, family, corpus, key, name, deps = line
            bridges.setdefault(f"{family} {corpus} {key}", []).append((name, set(filter(None, deps.split(",")))))
        elif line[0] == "DECIDABLE":
            _, family, corpus, key, name, deps = line
            decidables.setdefault(f"{family} {corpus} {key}", []).append((name, set(filter(None, deps.split(",")))))
        elif line[0] == "CHECKER":
            _, family, corpus, key, pairs = line
            generics[f"{family} {corpus} {key}"] = frozenset(tuple(p) for p in json.loads(pairs))
    problems, covered, declared_by_family, preconditions, used_allow = [], {}, {}, {}, set()
    identity = {}
    for (family, corpus, key), entry in checkers.items():
        where, uses = f"{family} {corpus} {key}", reached.get((family, corpus, key), set())
        if where in generics:
            identity[(corpus, entry["function"], generics[where])] = where
        names = {name for name, _, _ in entry["declared"]}
        declared_by_family.setdefault(family, set()).update(names)
        if not names:
            problems.append(f"{where}: declares no decided models")
        identified = {}
        for name, in_env, in_code in entry["declared"]:
            if name not in owners:
                problems.append(f"{where}: {name} is not a registered contract, reference or family")
                continue
            if in_env != "true":
                problems.append(f"{where}: {name} does not exist")
            elif in_code != "true":
                problems.append(f"{where}: {name} is not used by the decision code of this checker (check, checkModels)")
            decided = [m for m in sorted(owners[name]) if len(owners[name]) == 1
                       or (models[m]["receiver"] == name and models[m]["projection"] in uses)]
            if not decided:
                problems.append(f"{where}: {name} is shared by {sorted(owners[name])} and identifies none of "
                                "them in this checker")
            identified[name] = decided
            for m in decided:
                covered.setdefault(m, []).append(where)
                if entry["function"] not in models[m]["rust_names"]:
                    if (m, entry["function"]) in allow:
                        used_allow.add((m, entry["function"]))
                    else:
                        problems.append(f"{where}: declares {m}, whose source-map rust_names "
                                        f"{sorted(models[m]['rust_names']) or '(none)'} do not include "
                                        f"{entry['function']}; list the pair in cross-function.toml with a reason")
        for name in sorted(uses - names):
            for m in sorted(owners.get(name, ())):
                if entry["function"] in models[m]["rust_names"] and not models[m]["names"] & names:
                    problems.append(f"{where}: its decision code uses {name} of the model {m} (Rust "
                                    f"{entry['function']}), which it does not declare")
        for name in claimed.get((family, corpus, key), []):
            if name not in identified:
                problems.append(f"{where}: decidesRequires names {name}, which it does not declare (decides)")
                continue
            for m in identified[name]:
                contract = models[m]["contract"]
                found = []   # a trivial `requires` may be listed too (a family can list all it decides)
                if not REQUIRES_PROJECTIONS & uses:
                    found.append(f"it decides the precondition of {m}, but its decision code does not use "
                                 f"{REQUIRES_FIELD}")
                if contract not in uses:
                    found.append(f"it decides the precondition of {m}, but its decision code does not use "
                                 f"the registered contract {contract}")
                problems += [f"{where}: {f}" for f in found]
                if not found:
                    preconditions.setdefault(m, set()).add(where)
    return {"problems": problems, "covered": covered, "preconditions": preconditions,
            "declared": {f: sorted(ns) for f, ns in declared_by_family.items()},
            "used_allow": used_allow, "bridges": bridges, "decidables": decidables, "identity": identity,
            "reached": {f"{f} {c} {k}": names for (f, c, k), names in reached.items()}}


def requires_problems(covered: dict, preconditions: dict, requires: dict, models: dict,
                      open_listing: dict, complete: bool) -> list[str]:
    """A decided model whose `requires` does not reduce to True must have its precondition decided by
    each of its checkers (`decidesRequires`) or be listed in requires-open.toml, and only then."""
    problems = []
    for m in sorted(covered):
        if requires.get(models[m]["contract"], {}).get("requires") == "trivial":
            if m in open_listing:
                problems.append(f"{m} is listed in requires-open.toml, but its requires reduces to True")
            continue
        undecided = sorted(set(covered[m]) - preconditions.get(m, set()))
        if not undecided and m in open_listing:
            problems.append(f"{m} is listed in requires-open.toml, but each of its checkers decides its "
                            "precondition; remove the listing")
        elif undecided and m not in open_listing:
            problems.append(f"{m} has a non-trivial requires that {undecided[0]}"
                            + (f" (and {len(undecided) - 1} more)" if len(undecided) > 1 else "")
                            + " does not decide (decidesRequires) and requires-open.toml does not list")
    if complete:
        for m in sorted(set(open_listing) - set(covered)):
            problems.append(f"{m} is listed in requires-open.toml but decided by no checker")
    return problems


def theorem_class(theorem: str, model: str, wheres, audit: dict, data: dict, models: dict) -> tuple[str | None, str]:
    """Classify a listed theorem for `model` against the checkers `wheres` deciding its precondition.

    `negative`: its statement is `¬ P` or `b = false`, where `P` or `b` is the `requires` of the model, a
    predicate the `requires` unfolds to, or a decider of the model. `trivial`: `P ↔ True` or `P`, where `P`
    is the `requires` of the model at the index the checker uses. Either way the theorem must use a decider of
    the model: a declaration of the code of the checker that mentions `requires` and the contract of the model
    (directly or through one family alias), or a family declaration such a decider uses directly. Where the deciders of the
    checker are generic (none mentions the contract), a theorem stating the `requires` of the model
    at the index of the checker may use any of them. Otherwise None, with the reason."""
    contract = models[model]["contract"]
    if data["theorems"].get(theorem) != ("true", "true"):
        return None, "is not a theorem of the checked modules"
    shape, head, target, index, unfolded = data["shapes"].get(theorem, ("missing", "", set(), set(), set()))
    unfolds_to = {c for c in data["requires_uses"].get(contract, set())
                  if c.startswith(("Solanalib.Contracts.Model.", "Solanalib.Specs.Core.", "SolanalibTest.Conformance.Library.Families."))
                  and c not in REQUIRES_PROJECTIONS}
    specific, generic = set(), set()
    for w in wheres:
        for bridge, deps in audit["bridges"].get(w, []):
            family = {d for d in deps if d.startswith("SolanalibTest.Conformance.Library.Families.")}
            generic |= {bridge} | family
            if contract in deps:
                specific |= {bridge} | family
        for decidable, deps in audit["decidables"].get(w, []):
            # A family decision procedure of the contract or of a predicate its `requires` unfolds to.
            if contract in deps or deps & unfolds_to:
                specific.add(decidable)
    about = bool(REQUIRES_PROJECTIONS & target) and contract in target
    about_predicate = head in unfolds_to
    at_index = not index or any(index <= audit["reached"].get(w, set()) or (unfolded and unfolded <= audit["reached"].get(w, set()))
                                for w in wheres)
    # Generic deciders (none mentions the model): a negative theorem about the precondition of the model may use one
    # at any index (it shows the decider rejects); a trivial-at-index theorem only at the index of the checker.
    negative_shape = shape in ("not", "false")
    deciders = specific or (generic if (negative_shape and (about or about_predicate)) or (about and at_index) else set())
    if not deciders:
        return None, (f"no checker deciding the precondition of {model} has a decider that mentions {contract}"
                      + ("" if about else ", and the theorem does not state its `requires`")
                      + ("" if at_index else " at the index of the checker"))
    uses = data["uses"].get(theorem, set()) | target
    if not uses & deciders:
        return None, f"does not use a decider of the precondition of {model}"
    if negative_shape:
        if about or about_predicate or target & deciders:
            return "negative", ""
        return None, f"its negative statement is not about the precondition of {model}"
    if shape in ("iff_true", "positive"):
        if not about:
            return None, f"its statement ({shape}) is not about the precondition of {model}"
        if not at_index:
            return None, "its statement is not at the index the checker decides"
        return "trivial", ""
    return None, f"its statement has no usable shape ({shape})"


def precondition_evidence(audit: dict, requires: dict, models: dict, data: dict,
                          requires_theorems: list[dict], precondition_controls: dict | None,
                          complete: bool) -> tuple[list[str], dict]:
    """Each decided non-trivial precondition must be exercised by a family control that a checker deciding it
    must reject as outside the precondition (`precondition_controls`: (corpus, function, generics) -> labels),
    or by a listed negative theorem, or be trivial at the decided index by a listed theorem."""
    problems, evidence, classes = [], {}, {}
    controls_of = {}
    for ident, labels in (precondition_controls or {}).items():
        where = audit["identity"].get(ident)
        if where is not None:
            controls_of.setdefault(where, []).extend(labels)
    for t in requires_theorems:
        if t["model"] not in audit["preconditions"]:
            if complete:
                problems.append(f"requires-theorems.toml: {t['model']} is not a model whose precondition a checker decides")
            continue
        found, why = theorem_class(t["theorem"], t["model"], audit["preconditions"][t["model"]], audit, data, models)
        if found != t["kind"]:
            listed = "[[theorem]] (negative)" if t["kind"] == "negative" else "[[trivial]]"
            problems.append(f"requires-theorems.toml: {t['theorem']} is listed as {listed} for {t['model']} but "
                            + (f"is {found}" if found else why))
        else:
            classes.setdefault(t["model"], []).append(t)
    for m in sorted(audit["preconditions"]):
        if requires.get(models[m]["contract"], {}).get("requires") == "trivial":
            continue
        wheres = sorted(audit["preconditions"][m])
        labels = sorted({label for w in wheres for label in controls_of.get(w, [])})
        negative = [t["theorem"] for t in classes.get(m, []) if t["kind"] == "negative"]
        trivial = [t["theorem"] for t in classes.get(m, []) if t["kind"] == "trivial"]
        evidence[m] = {"controls": labels, "theorems": negative, "trivial_at_index": trivial}
        if precondition_controls is not None and not labels and not negative and not trivial:
            problems.append(f"{m}: its precondition is decided by {wheres[0]}"
                            + (f" (and {len(wheres) - 1} more)" if len(wheres) > 1 else "")
                            + ", but no family control has that checker reject a record as outside the precondition "
                              "and requires-theorems.toml lists no negative theorem using its decider")
    return problems, evidence


def checked_decides(output: str, models: dict, not_tested: list[dict] | None = None,
                    complete: bool = False, requires_open: list[dict] | None = None,
                    cross_function: list[dict] | None = None, requires_theorems: list[dict] | None = None,
                    precondition_controls: dict | None = None, corpora: set[str] | None = None) -> dict:
    """Check the per-checker declarations, the controls of the audit, the cross-function declarations, the
    preconditions (each decided by its checkers and exercised, or listed in `requires_open`) and, when
    `complete` (every family checked), that the registered models no checker decides are exactly
    `not_tested`. `precondition_controls` None skips the exercise check (unit tests). `corpora`
    scopes checker obligations to the selected records; audit controls always remain checked.
    Lean still checks the reflected code of the full family against its evaluated checker list."""
    kinds = {"DECIDES", "REACHES", "PRECONDITION", "BRIDGE", "DECIDABLE", "CHECKER"}
    records = [line.split("\t") for line in output.splitlines()]
    if corpora is not None:
        records = [fields for fields in records if fields[0] not in kinds
                   or fields[1].startswith("control:") or fields[2] in corpora]
    lines = [fields for fields in records if fields[0] in kinds]
    require(any(line[0] == "DECIDES" for line in lines), "missing checker-declaration report")
    requires = {}
    data = {"theorems": {}, "shapes": {}, "uses": {}, "requires_uses": {}, "family": set()}
    split = lambda text: set(filter(None, text.split(",")))
    for fields in records:
        if fields[0] == "REQUIRES":
            _, contract, kind, *text = fields
            requires[contract] = {"requires": kind, **({"text": text[0]} if text else {})}
        elif fields[0] == "REQUIRESUSES":
            data["requires_uses"][fields[1]] = split(fields[2])
        elif fields[0] == "THEOREM":
            data["theorems"][fields[1]] = (fields[2], fields[3])
        elif fields[0] == "THEOREMSHAPE":
            _, name, shape, head, target, index, unfolded = fields
            data["shapes"][name] = (shape, head, split(target), split(index), split(unfolded))
        elif fields[0] == "THEOREMUSES":
            data["uses"][fields[1]] = split(fields[2])
            data["family"] |= data["uses"][fields[1]]
        elif fields[0] == "BRIDGE":
            data["family"] |= {d for d in split(fields[5]) if d.startswith("SolanalibTest.Conformance.Library.Families.")}
    allow = {(e["model"], e["function"]) for e in (cross_function or [])}
    groups = {}
    for line in lines:
        groups.setdefault(line[1].startswith("control:") and line[1], []).append(line)
    audit = decides_problems(groups.pop(False, []), models, requires, allow)
    problems, covered = audit["problems"], audit["covered"]
    controls = []
    for index, control in enumerate(DECIDES_CONTROLS):
        group = groups.pop(f"control:{index}", None)
        if group is None:
            continue
        found = decides_problems(group, models, requires, allow)["problems"]
        missing = [e for e in control["expected"] if not any(e in p for p in found)]
        require(not missing, f"decides control '{control['label']}' was not rejected: missing {missing}; "
                             f"reported {found}")
        controls.append({"control": f"decides audit: {control['label']}", "problems": found})
    require(not groups, f"unexpected audit groups {sorted(groups)}")
    if complete:
        for model, function in sorted(allow - audit["used_allow"]):
            problems.append(f"cross-function.toml: no checker of {function} declares {model}; remove the entry")
    listed = {e["id"]: e for e in (not_tested or [])}
    for model in sorted(set(listed) & set(covered)):
        problems.append(f"{model} is listed in not-tested.toml but decided by {covered[model][0]}")
    if complete:
        for model in sorted(set(models) - set(covered) - set(listed)):
            problems.append(f"{model} is decided by no checker and not listed in not-tested.toml")
    open_listing = {e["id"]: e for e in (requires_open or [])}
    problems += requires_problems(covered, audit["preconditions"], requires, models, open_listing, complete)
    found, evidence = precondition_evidence(audit, requires, models, data, requires_theorems or [],
                                            precondition_controls, complete)
    problems += found
    # Controls of the theorem evidence: a theorem `True` proved by `decide` listed under a decided precondition,
    # and a theorem listed as trivial at the index offered as negative evidence, must both be rejected.
    decided_with_deciders = [m for m in sorted(audit["preconditions"])
                             if requires.get(models[m]["contract"], {}).get("requires") != "trivial"
                             and any(models[m]["contract"] in deps for w in audit["preconditions"][m]
                                    for _, deps in audit["bridges"].get(w, []))]
    if TRUE_BY_DECIDE in data["theorems"] and decided_with_deciders:
        # Exercise a `HasAccount` precondition of AccountsV2 when it is checked.
        preferred = [m for m in decided_with_deciders if m.startswith("solana-account-view::AccountView::Pool::")]
        m = (preferred or decided_with_deciders)[0]
        found, why = theorem_class(TRUE_BY_DECIDE, m, audit["preconditions"][m], audit, data, models)
        require(found is None, f"theorem control: `True` by decide was accepted as evidence for {m}")
        controls.append({"control": f"preconditions: `True` by decide listed for {m} is rejected", "problems": [why]})
    for t in [t for t in requires_theorems or [] if t["kind"] == "trivial" and t["model"] in audit["preconditions"]][:1]:
        found, why = theorem_class(t["theorem"], t["model"], audit["preconditions"][t["model"]], audit, data, models)
        require(found != "negative", f"theorem control: {t['theorem']} (trivial at the index) was accepted as negative evidence")
        controls.append({"control": f"preconditions: {t['theorem']} offered as negative evidence is rejected",
                         "problems": [f"is {found}" if found else why]})
    # Control: an undecided non-trivial precondition without a listing fails the run. With a needed listing,
    # drop it; otherwise take a decided precondition and drop the decision of one checker of it.
    nontrivial = lambda m: requires.get(models[m]["contract"], {}).get("requires") != "trivial"
    needed = [m for m in open_listing if m in covered and nontrivial(m)
              and set(covered[m]) - audit["preconditions"].get(m, set())]
    decided = [m for m in sorted(covered) if nontrivial(m) and m not in open_listing
               and set(covered[m]) <= audit["preconditions"].get(m, set())]
    if needed:
        model = needed[0]
        rest = {k: v for k, v in open_listing.items() if k != model}
        found = requires_problems(covered, audit["preconditions"], requires, models, rest, complete)
        label = f"preconditions: {model} without its requires-open.toml listing"
    elif decided:
        model = decided[0]
        weakened = {**audit["preconditions"], model: audit["preconditions"][model] - {covered[model][0]}}
        found = requires_problems(covered, weakened, requires, models, open_listing, complete)
        label = f"preconditions: {model} with {covered[model][0]} not deciding it and no listing"
    else:
        model, found, label = None, [], None
    if model is not None:
        require(any(f.startswith(f"{model} has a non-trivial requires") for f in found),
                f"requires control was not rejected: {label}")
        controls.append({"control": label, "problems": [f for f in found if f.startswith(model)]})
    require(not problems, "checker declarations:\n  " + "\n  ".join(problems[:40])
            + (f"\n  ... and {len(problems) - 40} more" if len(problems) > 40 else ""))
    kind = lambda m: requires.get(models[m]["contract"], {}).get("requires", "absent")
    return {"declared": audit["declared"], "registered_models": len(models), "decided_models": len(covered),
            "not_tested": sorted(listed), "requires_open": sorted(set(open_listing) & set(covered)),
            "complete": complete,
            "models": {m: {"checkers": covered[m], "requires": kind(m),
                           "precondition_decided_by": sorted(audit["preconditions"].get(m, ())),
                           **({"precondition_exercised_by": evidence[m]} if m in evidence else {})}
                       for m in sorted(covered)},
            "requires": requires, "controls": controls}


def checked_axioms(output: str) -> dict:
    """Every declaration of the modules of the checker uses only the allowed axioms."""
    lines = [line for line in output.splitlines() if line.startswith("AXIOMS ")]
    require(lines, "missing axiom report")
    report, theorems = {}, []
    for line in lines:
        match = re.fullmatch(r"AXIOMS (theorem|definition) (\S+) \[(.*)\]", line)
        require(match is not None, f"malformed axiom line: {line}")
        names = [n.strip() for n in match[3].split(",") if n.strip()]
        require(set(names) <= ALLOWED_AXIOMS, f"{match[2]} uses unapproved axioms {sorted(set(names) - ALLOWED_AXIOMS)}")
        report[match[2]] = names
        if match[1] == "theorem":
            theorems.append(match[2])
    return {"declarations": len(report), "theorems": sorted(theorems), "axioms": report}


def lean_command(source: Path, run_args: list[str] | None = None) -> list[str]:
    """Use ordinary Lean lookup in the single root package."""
    command = ["lake", "env", "lean", "-DwarningAsError=true"]
    if run_args is None:
        return [*command, str(source)]
    return [*command, "--run", str(source), *run_args]


class Checker:
    """The compiled executable over the whole registry, or the interpreter over selected families."""

    def __init__(self, runner: "Runner", families: list[str] | None):
        self.runner = runner
        self.families = families
        self.selection = None
        self.omitted_controls = []
        if families is not None:
            imports = "".join(f"import SolanalibTest.Conformance.Library.Families.{f}\n" for f in families)
            entries = " ++ ".join(f"SolanalibTest.Conformance.Library.Families.{f}.corpora" for f in families) or "[]"
            self.driver = runner.evidence / "Selected.lean"
            self.driver.write_text(f"import SolanalibTest.Conformance.Library.Runner\n{imports}\n"
                                   f"def main (args : List String) : IO UInt32 :=\n"
                                   f"  SolanalibTest.Conformance.Library.runMain ({entries}) args\n")

    def build(self) -> None:
        # The axiom and decides audit imports DECIDES_IMPORTS too; build those modules here, since no
        # checker imports them and a fresh checkout would not have their object files.
        audit_modules = [line.split()[1] for line in DECIDES_IMPORTS.splitlines() if line.startswith("import ")]
        if self.families is None:
            self.runner.run("build", ["lake", "--wfail", "build", "SolanalibTest.Conformance.Library", EXE, *audit_modules], REPO)
        else:
            modules = ["SolanalibTest.Conformance.Library.Runner"] + [f"SolanalibTest.Conformance.Library.Families.{f}" for f in self.families]
            self.runner.run("build", ["lake", "--wfail", "build", *modules, *audit_modules], REPO)

    divergences: Path | None = None
    spare_writes: Path | None = None

    def records(self, corpus: str, records: list) -> list:
        if self.selection is None:
            return records
        wanted = set(self.selection["corpora"][corpus]["selected_ids"])
        return [record for record in records if record["id"] in wanted]

    def mutate_selected(self, corpus: str, mutate):
        if self.selection is None:
            return mutate
        wanted = set(self.selection["corpora"][corpus]["selected_ids"])
        def selected(records):
            chosen = [record for record in records if record["id"] in wanted]
            omitted = [record for record in records if record["id"] not in wanted]
            mutate(chosen)
            records[:] = chosen + omitted
        return selected

    def run(self, name: str, corpus: Path, only: list[str] | None, registered: bool = False,
            divergences: Path | None | bool = True, describe: bool = False) -> tuple[int, str]:
        """`divergences`: True for the list of the run, a path for another list, False/None for none."""
        if self.selection is not None and self.selection.get("complete") and only is None and not describe:
            checker_selection.check_corpus_files(corpus, self.selection)
            only = sorted(set(self.selection["corpora"]) - set(self.selection["omitted_corpora"]))
        tail = ["--only", ",".join(only)] if only else (["--registered"] if registered else [])
        if describe:
            tail += ["--describe-checkers"]
        if self.selection is not None:
            omissions = [row for row in self.selection["omissions"] if not only or row["corpus"] in only]
            listing = self.runner.evidence / f"omissions-{name}.json"
            write_json(listing, omissions)
            tail += ["--omit-records", str(listing)]
        if self.spare_writes is not None:
            writers = [w for w in json.loads(self.spare_writes.read_text()) if not only or w["corpus"] in only]
            if self.selection is not None:
                writers = [w for w in writers if any(glob_match(w["function"], c["function"])
                           for c in self.selection["corpora"].get(w["corpus"], {}).get("checkers", []))]
            listing = self.runner.evidence / f"spare-writes-{name}.json"
            write_json(listing, writers)
            tail += ["--spare-writes", str(listing)]
            regionless = self.runner.evidence / f"regionless-{name}.json"
            write_json(regionless, regionless_corpora())
            tail += ["--regionless", str(regionless)]
        listing = self.divergences if divergences is True else (divergences or None)
        if listing is not None and only:
            entries = [e for e in json.loads(Path(listing).read_text()) if e["corpus"] in only]
            listing = self.runner.evidence / f"divergences-{name}.json"
            write_json(listing, entries)
        if listing is not None:
            tail += ["--divergences", str(listing)]
        if self.families is None:
            argv = [str(REPO / ".lake/build/bin" / EXE), str(corpus), *tail]
        else:
            argv = lean_command(self.driver, [str(corpus), *tail])
        return self.runner.run(name, argv, REPO, check=False)

    def audit_imports(self) -> str:
        if self.families is None:
            return "import SolanalibTest.Conformance.Library\n" + DECIDES_IMPORTS
        return "import SolanalibTest.Conformance.Library.Runner\n" + "".join(
            f"import SolanalibTest.Conformance.Library.Families.{f}\n" for f in self.families) + DECIDES_IMPORTS


COUNT_LINE = re.compile(r"\s+(ok  |FAIL) (\d+)/(\d+)(?: \[(\d+) known divergent\])?  (.*?)  -> (.+)$")


def parse_counts(output: str) -> dict:
    counts, current = {}, None
    for line in output.splitlines():
        if line and not line.startswith(" ") and not line.startswith(("All ", "MISMATCH", "FAIL", "OMITTED\t", "CHECKERS\t")) \
                and "failure(s)" not in line:
            current = line.strip()
            counts[current] = {}
        match = COUNT_LINE.match(line)
        if match and current:
            counts[current][match[5]] = {"admitted": int(match[2]), "total": int(match[3]),
                                         "divergent": int(match[4] or 0), "reference": match[6]}
        elif current and line.startswith(("  ok ", "  FAIL ")):
            raise ValueError(f"unparsable count line: {line!r}")
    return counts


def check_counts(counts: dict, summaries: dict) -> None:
    """Every checked corpus and every one of its records must appear in the parsed report
    (`summaries`: the authenticated manifest summaries of the checked corpora)."""
    require(set(counts) == {Path(name).stem for name in summaries},
            "count report corpora differ from the committed corpus")
    for name, summary in summaries.items():
        total = sum(entry["total"] for entry in counts[Path(name).stem].values())
        require(total == summary["records"],
                f"{name}: count report has {total} records, expected {summary['records']}")


# Negative controls: each mutation of the corpus must make the checker fail with this message.
class NoControlTarget(ValueError):
    """A well-formed control has no matching record in this selection."""


def _first(records: list, predicate) -> dict:
    for r in records:
        if predicate(r):
            return r
    raise NoControlTarget("no record matches the predicate of the control")


def _mutate_ok_value(records):
    r = _first(records, lambda r: r["outcome"].get("exit") == "returned"
               and isinstance(r["outcome"].get("result"), dict) and isinstance(r["outcome"]["result"].get("ok"), int))
    r["outcome"]["result"]["ok"] += 1


def _mutate_remaining(records):
    r = _first(records, lambda r: isinstance(r["outcome"].get("state"), dict) and r["outcome"]["state"].get("slice") == ""
               and r["state"].get("slice") and "err" in (r["outcome"].get("result") or {}))
    r["outcome"]["state"]["slice"] = r["state"]["slice"]


def _mutate_error_kind(records):
    r = _first(records, lambda r: "err" in (r["outcome"].get("result") or {}) and isinstance(r["outcome"]["result"]["err"], dict))
    r["outcome"]["result"]["err"]["kind"] = "Other" if r["outcome"]["result"]["err"]["kind"] != "Other" else "InvalidData"


def _mutate_error_message(records):
    r = _first(records, lambda r: "err" in (r["outcome"].get("result") or {}) and isinstance(r["outcome"]["result"]["err"], dict))
    r["outcome"]["result"]["err"]["message"] += "."


def _mutate_writer_event(records):
    r = _first(records, lambda r: len((r["outcome"].get("state") or {}).get("events", [])) > 0)
    r["outcome"]["state"]["events"].pop()


def _mutate_unwound(records):
    r = _first(records, lambda r: r["outcome"].get("exit") == "returned")
    r["outcome"] = {"exit": "unwound", "reason": "control", "state": r["outcome"]["state"]}


def _mutate_function(records):
    records[0]["function"] = records[0]["function"] + "_unregistered"


def _mutate_drop_function(records):
    victim = records[-1]["function"], records[-1]["generics"]
    records[:] = [r for r in records if (r["function"], r["generics"]) != victim]


def _mutate_layout(records):
    r = _first(records, lambda r: "layout" in r)
    r["layout"]["align"] = r["layout"]["align"] * 2


CONTROLS = [
    ("ok value", "borsh_0_10_4", _mutate_ok_value, "MISMATCH"),
    ("remaining slice after an error", "borsh_1_6_1", _mutate_remaining, "MISMATCH"),
    ("error kind", "borsh_0_10_4", _mutate_error_kind, "MISMATCH"),
    ("error message", "solana_stake_interface_3_1_0", _mutate_error_message, "MISMATCH"),
    ("writer chunk", "borsh_1_6_1", _mutate_writer_event, "MISMATCH"),
    ("unwound exit for a family without unwinding", "solana_address_2_6_0", _mutate_unwound, "MISMATCH"),
    ("unregistered function", "bytemuck_1_25_2", _mutate_function, "no registered checker"),
    ("checker without records", "borsh_1_6_1", _mutate_drop_function, "no records for"),
    ("layout of the index", "bytemuck_1_25_0", _mutate_layout, "layout mismatch"),
]


def selected_fixed_controls(checker: Checker, corpus: Path, checked: set[str]) -> list:
    """Retain fixed controls with selected targets; diagnose malformed controls.

Only the explicit absence of a target can omit a control. The same mutation
must succeed on the complete authenticated input, so missing full-corpus
targets and malformed mutations remain failures.
"""
    controls = []
    for control in CONTROLS:
        label, name, mutate, _ = control
        if name not in checked:
            continue
        if checker.selection is not None:
            records = json.loads((corpus / f"{name}.json").read_text())["records"]
            try:
                mutate(copy.deepcopy(checker.records(name, records)))
            except NoControlTarget:
                full = copy.deepcopy(records)
                mutate(full)
                changed = [r["id"] for r, after in zip(records, full) if r != after]
                require(changed, f"fixed control '{label}' changed no complete-corpus record")
                checker.omitted_controls.append({"kind": "fixed", "label": label, "corpus": name,
                    "reason": "target absent from selected records", "full_target_ids": changed})
                continue
        controls.append(control)
    return controls


# Sensitivity controls for the runtime record kinds. For every function instantiation of a corpus,
# the first record that has the kind (and is not a listed divergence) is mutated; all mutations of a
# kind go into one copy of the corpus, and the checker must reject each mutated record (MISMATCH or
# FAIL of that id), unless the driver of the corpus declares the kind unobserved in its driver.toml
# (`unobserved = ["syscalls"]`, with a comment saying why the models do not observe it).
def _state_after(r):
    return r["outcome"].get("state") if isinstance(r["outcome"].get("state"), dict) else {}


def _log_of(r):
    """The request log recorded after the call: the log of the shim (also on a terminated exit) or of a host stub."""
    if r["outcome"].get("exit") == "terminated":
        return ((r["outcome"].get("syscalls") or {}).get("log")) or None
    state = _state_after(r)
    for key in ("syscalls", "stubs"):
        log = (state.get(key) or {}).get("log") if isinstance(state.get(key), dict) else None
        if log:
            return log
    return None


def _has_log(r):
    return _log_of(r) is not None


def _mutate_log(r):
    _log_of(r).pop()


REGION_KEYS = ("input", "region")


def _region_accounts(r):
    state = _state_after(r)
    for key in REGION_KEYS:
        if isinstance(state.get(key), dict) and isinstance(state[key].get("accounts"), list):
            return state[key]["accounts"]
    if isinstance(state.get("accounts"), list):
        return state["accounts"]
    return []


def _has_region(r):
    return any(isinstance(a, dict) and "lamports" in a for a in _region_accounts(r))


def _mutate_region(r):
    account = next(a for a in _region_accounts(r) if isinstance(a, dict) and "lamports" in a)
    account["lamports"] += 1


# Spare bytes: the `spare` of an account read back after the call (every byte from `data_len` to the
# original length plus the 10 KiB realloc padding). Flipping one byte deep in the realloc padding,
# or the last spare byte, of the first account that has it must be rejected. The flip keeps the
# recorded summary `spare_nonzero_at` consistent, so the models, not the reader, must notice it.
DEEP_SPARE = 3000


def _spare_account(r, at_least):
    for a in _region_accounts(r):
        if isinstance(a, dict) and isinstance(a.get("spare"), str) and len(expand_hex(a["spare"])) >= at_least:
            return a
    return None


def _flip_spare(account, offset):
    spare = bytearray(expand_hex(account["spare"]))
    spare[offset] ^= 0x01
    account["spare"] = compact_hex(bytes(spare))
    if "spare_nonzero_at" in account:
        first = next((i for i, b in enumerate(spare) if b), None)
        shown = len(expand_hex(account["data"])) if isinstance(account.get("data"), str) else 0
        account["spare_nonzero_at"] = None if first is None else shown + first


def _has_deep_spare(r):
    return _spare_account(r, DEEP_SPARE + 1) is not None


def _mutate_deep_spare(r):
    _flip_spare(_spare_account(r, DEEP_SPARE + 1), DEEP_SPARE)


def _has_spare(r):
    return _spare_account(r, 1) is not None


def _mutate_last_spare(r):
    _flip_spare(_spare_account(r, 1), -1)


def _spare_summary(account, spare):
    first = next((i for i, b in enumerate(spare) if b), None)
    shown = len(expand_hex(account["data"])) if isinstance(account.get("data"), str) else 0
    return None if first is None else shown + first


def _set_spare(account, spare):
    account["spare"] = compact_hex(bytes(spare))
    if "spare_nonzero_at" in account:
        account["spare_nonzero_at"] = _spare_summary(account, spare)


def _later_spare_account(r):
    """An account after the call with a nonzero spare byte followed by another spare byte."""
    for a in _region_accounts(r):
        if isinstance(a, dict) and isinstance(a.get("spare"), str):
            spare = expand_hex(a["spare"])
            first = next((i for i, b in enumerate(spare) if b), None)
            if first is not None and first + 1 < len(spare):
                return a
    return None


def _flip_last_spare(account):
    spare = bytearray(expand_hex(account["spare"]))
    spare[-1] ^= 0x01
    _set_spare(account, spare)


def _region_before(r):
    """The read-back region before the call (state key `input` or `region`, with a count word)."""
    state = r.get("state") if isinstance(r.get("state"), dict) else {}
    for key in REGION_KEYS:
        if isinstance(state.get(key), dict) and "count" in state[key] and isinstance(state[key].get("accounts"), list):
            return state[key]
    return None


def _spare_pair(r):
    """The index of the first account whose read-back spare bytes before and after the call have the same
    length of at least two bytes, or None."""
    before = _region_before(r)
    if before is None:
        return None
    for i, (b, a) in enumerate(zip(before["accounts"], _region_accounts(r))):
        if isinstance(b.get("spare"), str) and isinstance(a.get("spare"), str):
            if len(expand_hex(b["spare"])) == len(expand_hex(a["spare"])) >= 2:
                return i
    return None


def _set_first_spare_both(r):
    """Make spare byte 0 of the paired account nonzero before and after the call (consistently)."""
    i = _spare_pair(r)
    for a in (_region_before(r)["accounts"][i], _region_accounts(r)[i]):
        spare = bytearray(expand_hex(a["spare"]))
        spare[0] |= 0x01
        _set_spare(a, spare)


def _read_back_after(r):
    state = _state_after(r)
    return next((state[k] for k in REGION_KEYS if isinstance(state.get(k), dict) and "count" in state[k]), None)


def _drop_count(r):
    del _read_back_after(r)["count"]


def _is_terminated(r):
    return r["outcome"].get("exit") == "terminated"


def _mutate_terminated(r):
    r["outcome"]["reason"] = "abort" if r["outcome"].get("reason") != "abort" else "sol_panic_"


KIND_CONTROLS = [
    ("syscalls", "request log after the call", _has_log, _mutate_log),
    ("input", "account region after the call", _has_region, _mutate_region),
    ("input", f"spare byte {DEEP_SPARE} (realloc padding) after the call", _has_deep_spare, _mutate_deep_spare),
    ("input", "last spare byte after the call", _has_spare, _mutate_last_spare),
    ("input", "account-count word dropped from the region after the call", lambda r: _read_back_after(r) is not None,
     _drop_count),
    ("terminated", "terminal exit reason", _is_terminated, _mutate_terminated),
]


def kind_targets(records: list, present, divergence_patterns: list[str]) -> list[str]:
    """The first record of each function instantiation that has the kind, outside listed divergences."""
    seen, targets = set(), []
    for r in records:
        key = (r["function"], json.dumps(r["generics"], sort_keys=True))
        if key in seen or any(glob_match(p, r["id"]) for p in divergence_patterns):
            continue
        if present(r):
            seen.add(key)
            targets.append(r["id"])
    return targets


def regionless_corpora() -> list[str]:
    """The corpora of drivers that declare `region = "none"`."""
    return sorted(c for spec in discover_drivers().values() if spec["regionless"] for c in spec["corpora"])


def spare_writers() -> list[dict]:
    """`{corpus, function}` for every function glob a driver lists in `spare_writes`, per corpus."""
    return [{"corpus": c, "function": f} for spec in discover_drivers().values()
            for c in spec["corpora"] for f in spec["spare_writes"]]


def _spare_after_nonzero_control(runner: Runner, checker: Checker, corpus: Path, name: str, records: list,
                                 patterns: list[str]) -> dict | None:
    """Flip the last spare byte after an earlier nonzero spare byte of an account after the call, with
    `spare_nonzero_at` kept consistent (it does not change), in the first record of each function
    instantiation; every flip must be rejected. Records that have such an account are used as they are.
    For a function without one, the first record whose regions before and after are read back gets spare
    byte 0 set before and after the call; that setup alone must be admitted (records whose setup is
    rejected are dropped and counted), and then the later byte is flipped."""
    natural = kind_targets(records, lambda r: _later_spare_account(r) is not None, patterns)
    covered = {(r["function"], json.dumps(r["generics"], sort_keys=True)) for r in records if r["id"] in natural}
    synthetic = [t for t in kind_targets(records, lambda r: _spare_pair(r) is not None, patterns)
                 if next((r["function"], json.dumps(r["generics"], sort_keys=True))
                         for r in records if r["id"] == t) not in covered]
    dropped = []
    setup_work, setup_code = None, None
    if synthetic:
        work = runner.evidence / f"control-spare-setup-{name}"
        work.mkdir(exist_ok=True)
        def setup(rs, targets=set(synthetic)):
            for r in rs:
                if r["id"] in targets:
                    _set_first_spare_both(r)
        apply_control(corpus, work, name, setup)
        setup_code, output = checker.run(f"control-spare-setup-{name}", work, [name])
        setup_work = work
        dropped = [t for t in synthetic if f"MISMATCH {name}/{t} " in output or f"FAIL {name}/{t}:" in output]
        synthetic = [t for t in synthetic if t not in dropped]
    if not natural and not synthetic:
        return None
    work = runner.evidence / f"control-spare-later-{name}"
    work.mkdir(exist_ok=True)
    def flip(rs, natural=set(natural), synthetic=set(synthetic)):
        for r in rs:
            if r["id"] in natural:
                _flip_last_spare(_later_spare_account(r))
            elif r["id"] in synthetic:
                _set_first_spare_both(r)
                _flip_last_spare(_region_accounts(r)[_spare_pair(r)])
    apply_control(corpus, work, name, flip)
    code, output = checker.run(f"control-spare-later-{name}", work, [name])
    targets = natural + synthetic
    missed = [t for t in targets if f"MISMATCH {name}/{t} " not in output and f"FAIL {name}/{t}:" not in output]
    require(code == 1 and not missed,
            f"spare byte after an earlier nonzero spare byte in {name}: flips in {len(missed)} of {len(targets)} "
            f"records were admitted, e.g. {missed[:3]}")
    _compact_control(runner, work)
    if setup_work is not None and setup_code == 0:
        _compact_control(runner, setup_work)
    return {"control": f"spare byte after an earlier nonzero spare byte in {name}", "corpus": name,
            "exit_code": code, "records": len(targets), "synthetic": len(synthetic),
            "synthetic_setup_rejected": len(dropped)}


# Semantic controls, one per checker: the outcome of the first record of every function instantiation
# (outside listed divergences) is changed in a type-preserving way, and that checker must reject it.
# The first changeable leaf of the returned `result` (in key order) changes: a number by one, a Boolean
# negated, a byte string in its first byte, a text or an enum value (`variant`) to another one recorded at
# the same path by the same function (else in the corpus). A `returned` outcome without such a leaf becomes
# an unwind; an unwind or a terminal exit changes its reason. Where the model genuinely admits that change,
# the family gives another mutation in controls/<Family>.py:
#
#     SEMANTIC = [(corpus, on_record(id, change), reason)]   # replaces the generic mutation for the
#                                                           # instantiation of record `id`
def _perturb(value, alternatives=None, path=()):
    """A type-preserving change of a JSON value, or None if it has no changeable leaf. A text leaf that is
    not a byte string takes another value recorded at the same path (`alternatives`), else is extended."""
    if isinstance(value, bool):
        return not value
    if isinstance(value, int):
        return value - 1 if value > 0 else value + 1
    if isinstance(value, float):
        return value + 1.0
    if isinstance(value, str):
        if value and COMPACT_HEX.match(value):
            data = bytearray(expand_hex(value))
            data[0] ^= 0x01
            return compact_hex(bytes(data))
        for table in alternatives or []:
            other = sorted(v for v in table.get(path, set()) - {value} if not v.startswith("{"))
            if other:
                return other[0]
        return None   # no other recorded text: another leaf, or the exit kind, changes instead
    if isinstance(value, list):
        for i, item in enumerate(value):
            changed = _perturb(item, alternatives, path + (i,))
            if changed is not None:
                return value[:i] + [changed] + value[i + 1:]
        return None
    if isinstance(value, dict):
        if "variant" in value:
            # A recorded enum value: take another variant recorded at the same path, with its own fields.
            for table in alternatives or []:
                other = sorted(v for v in table.get(path, set()) if isinstance(v, str) and v.startswith("{")
                               and json.loads(v).get("variant") != value["variant"])
                if other:
                    return json.loads(other[0])
        for key in sorted(value):
            changed = _perturb(value[key], alternatives, path + (key,))
            if changed is not None:
                return {**value, key: changed}
    return None


def text_alternatives(records: list) -> dict:
    """Every non-hex text recorded in a returned result, by its path in the result, and every recorded enum
    value (an object with `variant`), as JSON text."""
    found = {}
    def walk(value, path):
        if isinstance(value, dict) and "variant" in value:
            found.setdefault(path, set()).add(json.dumps(value, sort_keys=True))
        if isinstance(value, str) and not (value and COMPACT_HEX.match(value)):
            found.setdefault(path, set()).add(value)
        elif isinstance(value, list):
            for i, item in enumerate(value):
                walk(item, path + (i,))
        elif isinstance(value, dict):
            for key, item in value.items():
                walk(item, path + (key,))
    for r in records:
        if r["outcome"].get("exit") == "returned":
            walk(r["outcome"].get("result"), ())
    return found


def semantic_mutation(r, alternatives: list | None = None) -> str:
    """`alternatives`: text values by result path, in order of preference (see `text_alternatives`)."""
    """Change the outcome of the record in place (see above); return what changed."""
    outcome = r["outcome"]
    exit_kind = outcome.get("exit")
    if exit_kind == "returned":
        changed = _perturb(outcome.get("result"), alternatives)
        if changed is not None:
            outcome["result"] = changed
            return "result"
        r["outcome"] = {"exit": "unwound", "reason": "conformance control", "state": outcome.get("state")}
        return "returned -> unwound"
    if exit_kind == "terminated":
        outcome["reason"] = "abort" if outcome.get("reason") != "abort" else "sol_panic_"
        return "terminal reason"
    changed = _perturb(outcome.get("reason"))
    outcome["reason"] = changed if changed is not None else "conformance control"
    return "unwind reason"


def load_semantic_overrides(directory: Path = CONTROLS_DIR) -> list[dict]:
    """`SEMANTIC = [(corpus, on_record(id, change), reason)]` from controls/<Family>.py."""
    import importlib.util
    overrides = []
    if not directory.exists():
        return overrides
    sys.path.insert(0, str(directory))
    try:
        for path in sorted(directory.glob("*.py")):
            if path.stem == "common" or path.stem.startswith("_"):
                continue
            spec = importlib.util.spec_from_file_location(f"semantic_overrides_{path.stem}", path)
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            for entry in getattr(module, "SEMANTIC", []):
                require(isinstance(entry, tuple) and len(entry) == 3 and isinstance(entry[0], str)
                        and callable(entry[1]) and getattr(entry[1], "record_id", None)
                        and isinstance(entry[2], str) and entry[2].strip(),
                        f"{path}: each SEMANTIC entry is (corpus, on_record(id, change), reason)")
                overrides.append({"family": path.stem, "corpus": entry[0], "mutate": entry[1],
                                  "record": entry[1].record_id, "reason": entry[2]})
    finally:
        sys.path.remove(str(directory))
    return overrides


def _instantiation(r) -> tuple:
    return (r["function"], frozenset(r["generics"].items()))


def semantic_plan(records: list, patterns: list[str], overrides: list[dict]) -> list[dict]:
    """One mutation per function instantiation: the override mutation, else the generic one on its first record."""
    by_id = {r["id"]: r for r in records}
    replaced = {}
    for o in overrides:
        require(o["record"] in by_id, f"SEMANTIC override ({o['family']}): no record {o['record']} in {o['corpus']}")
        key = _instantiation(by_id[o["record"]])
        require(key not in replaced, f"SEMANTIC overrides ({o['family']}): two for the instantiation of {o['record']}")
        replaced[key] = o
    plan = []
    for target in kind_targets(records, lambda r: True, patterns):
        key = _instantiation(by_id[target])
        o = replaced.pop(key, None)
        plan.append({"record": o["record"], "override": o} if o else {"record": target, "override": None})
    require(not replaced, f"SEMANTIC overrides for instantiations without a target: {[o['record'] for o in replaced.values()]}")
    return plan


def _semantic_controls(runner: Runner, checker: Checker, corpus: Path, checked: set[str],
                       patterns: dict) -> list[dict]:
    overrides = load_semantic_overrides()
    results, admitted = [], []
    for name in sorted(checked):
        records = checker.records(name, json.loads((corpus / f"{name}.json").read_text())["records"])
        selected_ids = {r["id"] for r in records}
        selected_overrides = [o for o in overrides if o["corpus"] == name
                              and (checker.selection is None or o["record"] in selected_ids)]
        plan = semantic_plan(records, patterns.get(name, []), selected_overrides)
        changes, in_corpus = {}, text_alternatives(records)
        by_function = {}
        for r in records:
            by_function.setdefault(r["function"], []).append(r)
        by_function = {f: text_alternatives(rs) for f, rs in by_function.items()}
        def mutate_all(rs, plan=plan, changes=changes):
            for step in plan:
                r = next(r for r in rs if r["id"] == step["record"])
                if step["override"]:
                    step["override"]["mutate"]([r])
                    changes[step["record"]] = "override: " + step["override"]["reason"]
                else:
                    # Prefer a text recorded by the same function, then anywhere in the corpus.
                    changes[step["record"]] = semantic_mutation(r, [by_function[r["function"]], in_corpus])
        work = runner.evidence / f"control-semantic-{name}"
        work.mkdir(exist_ok=True)
        apply_control(corpus, work, name, mutate_all)
        code, output = checker.run(f"control-semantic-{name}", work, [name])
        # The model must reject the changed outcome (a MISMATCH); an override may also expect a FAIL.
        missed = [s["record"] for s in plan
                  if f"MISMATCH {name}/{s['record']} " not in output
                  and not (s["override"] and f"FAIL {name}/{s['record']}:" in output)]
        by_id = {r["id"]: r for r in records}
        for rid in missed:
            r = by_id[rid]
            admitted.append(f"{name}: {r['function']} {dict(r['generics'])} admits record {rid} with its "
                            f"{changes[rid]} changed")
        kinds = {}
        for change in changes.values():
            kinds[change.split(":")[0]] = kinds.get(change.split(":")[0], 0) + 1
        results.append({"control": f"semantic change of the first record of each checker in {name}", "corpus": name,
                        "exit_code": code, "records": len(plan), "changes": kinds,
                        "overrides": sum(1 for s in plan if s["override"]), "admitted": len(missed)})
        if code == 1 and not missed:
            _compact_control(runner, work)
    report = runner.evidence / "semantic-admitted.json"
    write_json(report, admitted)
    require(not admitted, f"semantic controls: {len(admitted)} checkers admit their changed first record "
                          f"(give an override with a reason in controls/<Family>.py SEMANTIC), see {report}:\n  "
                          + "\n  ".join(admitted[:30]))
    return results


def unobserved_kinds(corpus_name: str) -> set[str]:
    for spec in discover_drivers().values():
        if corpus_name in spec["corpora"]:
            return set(spec["unobserved"])
