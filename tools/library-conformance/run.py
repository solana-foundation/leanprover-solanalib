def load_model_listing(path: Path, models: dict | None = None) -> list[dict]:
    """`[[model]]` tables with `id` (a source-map model), `reason` and optional `detail`."""
    spec = tomllib.loads(path.read_text())
    require(set(spec) <= {"model"}, f"{path}: only [[model]] tables are allowed")
    items = spec.get("model", [])
    require(isinstance(items, list), f"{path}: [[model]] entries expected")
    registered = source_map() if models is None else models
    seen = set()
    for item in items:
        require(set(item) <= {"id", "detail", "reason"} and {"id", "reason"} <= set(item)
                and all(isinstance(v, str) and v.strip() for v in item.values()),
                f"{path}: each model has string `id`, `reason` and optional `detail`")
        require(item["id"] not in seen, f"{path}: {item['id']} is listed twice")
        require(item["id"] in registered, f"{path}: {item['id']} is not a registered model of the source map")
        seen.add(item["id"])
    return items


