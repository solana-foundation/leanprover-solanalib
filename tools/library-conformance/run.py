# A checker decides a model on the records of its own function: the source-map `rust_names` of the model must
# include the `function` of the checker. A model without `rust_names` (observations, shared models, supporting
# models) or decided on the records of another function is listed with that function (`cross-function.toml`):
#
#     [[allow]]
#     model = "shared-token::amount"                           # a source-map model id
#     function = "pinocchio_token::state::account::Account::amount"   # the `function` of the checker
#     detail = "TokenViews"                                    # the deciding family
#     reason = "..."
def load_cross_function(path: Path = CROSS_FUNCTION, models: dict | None = None) -> list[dict]:
    spec = tomllib.loads(path.read_text())
    require(set(spec) <= {"allow"}, f"{path}: only [[allow]] tables are allowed")
    items = spec.get("allow", [])
    registered = source_map() if models is None else models
    seen = set()
    for item in items:
        require(set(item) == {"model", "function", "detail", "reason"}
                and all(isinstance(v, str) and v.strip() for v in item.values()),
                f"{path}: each entry has string `model`, `function`, `detail` and `reason`")
        key = (item["model"], item["function"])
        require(key not in seen, f"{path}: {key} is listed twice")
        require(item["model"] in registered, f"{path}: {item['model']} is not a registered model of the source map")
        require(item["function"] not in registered[item["model"]]["rust_names"],
                f"{path}: {item['model']} already binds {item['function']} (rust_names); remove the entry")
        seen.add(key)
    return items


