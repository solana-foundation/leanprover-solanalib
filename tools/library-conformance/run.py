class Runner:
    def __init__(self, evidence: Path, timeout: int, control_jobs: int = 1):
        self.evidence = evidence
        self.timeout = timeout
        self.control_jobs = control_jobs
        self.commands: list[dict] = []
        self.command_lock = threading.Lock()
        self.environment = os.environ.copy()
        build_jobs = self.environment.get('CARGO_BUILD_JOBS')
        for key in list(self.environment):
            if key in {"RUSTFLAGS", "RUSTDOCFLAGS", "RUSTC", "RUSTDOC", "RUSTC_WRAPPER",
                       "RUSTC_WORKSPACE_WRAPPER", "RUSTUP_TOOLCHAIN", "CARGO_ENCODED_RUSTFLAGS",
                       "CARGO_ENCODED_RUSTDOCFLAGS"} or key.startswith(
                           ("CARGO_PROFILE_", "CARGO_BUILD_", "CARGO_TARGET_")):
                del self.environment[key]
        if build_jobs is not None:
            self.environment['CARGO_BUILD_JOBS'] = build_jobs
        self.environment["PYTHONDONTWRITEBYTECODE"] = "1"

    def run(self, name: str, arguments: list[str], cwd: Path, env: dict | None = None,
            check: bool = True, stdout_only: bool = False) -> tuple[int, str]:
        out, err = self.evidence / f"run-{name}.out", self.evidence / f"run-{name}.log"
        started = time.monotonic()
        with out.open("w") as stdout, err.open("w") as stderr:
            process = subprocess.Popen(arguments, cwd=cwd, env={**self.environment, **(env or {})},
                                       stdout=stdout, stderr=stderr, start_new_session=True)
            try:
                code = process.wait(timeout=self.timeout)
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGTERM)
                process.wait()
                code = 124
        with self.command_lock:
            self.commands.append({"name": name, "argv": arguments, "cwd": str(cwd), "exit_code": code,
                                  "elapsed_seconds": round(time.monotonic() - started, 3),
                                  "stdout": out.name, "stderr": err.name})
            write_json(self.evidence / "commands.json", self.commands)
        if check:
            require(code == 0, f"{name} failed with exit {code}; see {err} and {out}")
        return code, out.read_text() + ("" if stdout_only else err.read_text())


