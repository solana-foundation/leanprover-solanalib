def load_requires_theorems(path: Path = REQUIRES_THEOREMS, models: dict | None = None) -> list[dict]:
    """`[[theorem]]` (negative evidence) and `[[trivial]]` (trivial at the decided index) entries, each with
    `kind` set to `negative` or `trivial`."""
    spec = tomllib.loads(path.read_text())
    require(set(spec) <= {"theorem", "trivial"}, f"{path}: only [[theorem]] and [[trivial]] tables are allowed")
    registered = source_map() if models is None else models
    seen, items = set(), []
    for table, kind in (("theorem", "negative"), ("trivial", "trivial")):
        for item in spec.get(table, []):
            require(set(item) == {"model", "theorem", "detail", "reason"}
                    and all(isinstance(v, str) and v.strip() for v in item.values()),
                    f"{path}: each entry has string `model`, `theorem`, `detail` and `reason`")
