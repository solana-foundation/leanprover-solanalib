    for index, control in enumerate(DECIDES_CONTROLS):
        if control["family"] not in families:
            continue
        controls.append(f"def DecidesControl.c{index} : List (String × List SolanalibTest.Conformance.Library.Checker) :=\n"
                        f"  {control['corpora']}\n")
        entries.append(f'("control:{index}", `DecidesControl.c{index}, DecidesControl.c{index})')
    controls.append(f"theorem {TRUE_BY_DECIDE} : True := by decide\n")
