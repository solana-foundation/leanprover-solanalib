def family_modules(families: Path = FAMILIES) -> list[str]:
    """Top-level SolanalibTest/Conformance/Library/Families/<Name>.lean files that define `corpora`."""
    names = []
    for path in sorted(families.glob("*.lean")):
        text = path.read_text()
        if re.search(r"^def corpora\b", text, re.M):
            require(FAMILY_NAME.match(path.stem) is not None, f"{path.name}: family names are CamelCase")
            require(re.search(rf"^namespace SolanalibTest\.Conformance\.Library\.Families\.{re.escape(path.stem)}\s*$", text, re.M),
                    f"{path.name}: `corpora` must be in namespace SolanalibTest.Conformance.Library.Families.{path.stem}")
            names.append(path.stem)
    return names


def registry_source(families: list[str]) -> str:
    imports = "import SolanalibTest.Conformance.Library.Core\n" + "".join(
        f"import SolanalibTest.Conformance.Library.Families.{f}\n" for f in families)
    entries = " ++\n  ".join(f"Families.{f}.corpora" for f in families) or "[]"
    return format_source(HEADER + f"""{imports}
/-!
# Registered checkers, per corpus file (generated)

Generated by `run.py --generate-registry` from `SolanalibTest/Conformance/Library/Families/*.lean`; do not edit.
Each family module defines `SolanalibTest.Conformance.Library.Families.<Name>.corpora`.
-/

set_option autoImplicit false

namespace SolanalibTest.Conformance.Library

def registry : List (String × List Checker) :=
  {entries}

end SolanalibTest.Conformance.Library
""")


def generate_registry(write: bool = True) -> bool:
    """Return whether Registry.lean was already current; rewrite it when `write`."""
    source = registry_source(family_modules())
    current = REGISTRY.exists() and REGISTRY.read_text() == source
    if write and not current:
        REGISTRY.write_text(source)
    return current


