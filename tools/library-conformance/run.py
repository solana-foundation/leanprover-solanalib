def load_family_controls(directory: Path = CONTROLS_DIR) -> list[dict]:
    """Family controls from controls/<Family>.py (`CONTROLS = [(label, corpus, mutate[, expected])]`,
    helpers in controls/common.py). Each must make the checker fail with `expected` in its output."""
    import importlib.util
    controls = []
    if not directory.exists():
        return controls
    sys.path.insert(0, str(directory))
    try:
        for path in sorted(directory.glob("*.py")):
            if path.stem == "common" or path.stem.startswith("_"):
                continue
            spec = importlib.util.spec_from_file_location(f"family_controls_{path.stem}", path)
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            entries = getattr(module, "CONTROLS", None)
            require(isinstance(entries, list) and entries, f"{path}: CONTROLS must be a nonempty list")
            for entry in entries:
                require(isinstance(entry, tuple) and len(entry) in (3, 4) and isinstance(entry[0], str)
                        and isinstance(entry[1], str) and callable(entry[2]),
                        f"{path}: each control is (label, corpus, mutate[, expected])")
                label, corpus, mutate = entry[:3]
                rid = getattr(mutate, "record_id", None)
                require(not getattr(mutate, "precondition", False) or len(entry) == 4,
                        f"{path}: precondition control '{label}' must give the message of the checker as `expected`")
                expected = entry[3] if len(entry) == 4 else (f"MISMATCH {corpus}/{rid}" if rid else "MISMATCH")
                controls.append({"family": path.stem, "label": label, "corpus": corpus, "mutate": mutate,
                                 "expected": expected})
    finally:
        sys.path.remove(str(directory))
    return controls


def is_precondition_control(control: dict) -> bool:
    """Built with `outside_precondition`, or a record control whose `expected` names the precondition."""
    return getattr(control["mutate"], "record_id", None) is not None and (
        getattr(control["mutate"], "precondition", False) or "precondition" in control["expected"].lower())


def record_report(output: str, corpus: str, record_id: str) -> str:
    """The report of the checker of one record: its FAIL or MISMATCH line and the indented lines after it."""
    lines, block = output.splitlines(), []
    for i, line in enumerate(lines):
        if line.startswith((f"FAIL {corpus}/{record_id}:", f"MISMATCH {corpus}/{record_id} ")):
            block.append(line)
            block += [l for l in __import__("itertools").takewhile(lambda l: l.startswith("  "), lines[i + 1:])]
    return "\n".join(block)


def precondition_control_index(checked: set[str]) -> dict:
    """(corpus, function, generics) of the record each family precondition control mutates -> its labels.
    A precondition control expects its record to be rejected as outside a precondition (its `expected`
    names the precondition) and is built with `on_record`."""
    index, records = {}, {}
    for c in load_family_controls():
        if c["corpus"] not in checked or not is_precondition_control(c):
            continue
        if c["corpus"] not in records:
            records[c["corpus"]] = {r["id"]: r for r in json.loads((CORPUS / f"{c['corpus']}.json").read_text())["records"]}
        r = records[c["corpus"]].get(c["mutate"].record_id)
        if r is not None:
            ident = (c["corpus"], r["function"], frozenset(r["generics"].items()))
            index.setdefault(ident, []).append(f"{c['family']}: {c['label']}")
    return index


def copy_corpus(source: Path, target: Path) -> None:
    for p in source.glob("*.json"):
        shutil.copyfile(p, target / p.name)


def _control_baseline(runner: Runner, source: Path) -> None:
    """Keep one ordinary corpus copy for restoring compacted successful controls."""
    baseline = runner.evidence / "control-baseline"
    baseline.mkdir()  # Never merge a new run into a saved baseline.
    copy_corpus(source, baseline)
    require({p.name: sha256(p) for p in baseline.glob("*.json")} ==
            {p.name: sha256(p) for p in source.glob("*.json")},
            "control baseline differs from the source corpus")


def _compact_control(runner: Runner, target: Path) -> None:
    """After all checks pass, retain changed/extra files and discard only identical copies."""
    baseline = runner.evidence / "control-baseline"
    require(target.parent == runner.evidence and target != baseline and not target.is_symlink(),
            "control compaction needs a private control directory")
    originals = list(baseline.glob("*.json"))
    # A control that removes a whole file must retain that absence, without a restoration step.
    if any(not (target / p.name).is_file() for p in originals):
        return
    for original in originals:
        copied = target / original.name
        if not copied.is_symlink() and copied.read_bytes() == original.read_bytes():
            copied.unlink()


def apply_control(source: Path, target: Path, corpus_name: str, mutate) -> None:
    copy_corpus(source, target)
    path = target / f"{corpus_name}.json"
    data = json.loads(path.read_text())
    mutate(data["records"])
    path.write_text(json.dumps(data))


def unlisted_control_id(listed_id: str, patterns: list[str]) -> str | None:
    """An id for a copy of a listed record that no divergence glob of its corpus matches."""
    return next((c for c in (f"{listed_id}#control", f"control#{listed_id}", "control-unlisted")
                 if not any(glob_match(p, c) for p in patterns)), None)


def _divergence_controls(runner: Runner, checker: Checker, corpus: Path, divergences: list[dict]) -> list[dict]:
    """For each listed divergence: an unlisted copy of a listed record must mismatch (the listing masks
    nothing else); removing its records must fail (stale listing); unlisting it must make its records
    mismatch (the model does reject them)."""
    results = []
    for index, d in enumerate(divergences):
        records = checker.records(d["corpus"], json.loads((corpus / f"{d['corpus']}.json").read_text())["records"])
        listed = [r for r in records if glob_match(d["records"], r["id"])]
        if not listed:
            continue
        patterns = [e["records"] for e in divergences if e["corpus"] == d["corpus"]]
        fresh = unlisted_control_id(listed[0]["id"], patterns)
        require(fresh is not None, f"divergences/{d['corpus']}.toml: the glob `{d['records']}` also matches every id "
                                   "the unlisted-copy control could use; make it more specific")
        cases = []
        def copy_unlisted(rs, fresh=fresh, original=listed[0]):
            rs.append({**copy.deepcopy(original), "id": fresh})
        cases.append(("an unlisted copy of a listed record", copy_unlisted, True, "MISMATCH"))
        def drop_listed(rs, pattern=d["records"]):
            rs[:] = [r for r in rs if not glob_match(pattern, r["id"])]
        cases.append(("its records removed", drop_listed, True, "matches no record"))
        cases.append(("the divergence unlisted", None, False, "MISMATCH"))
        for label, mutate, keep_listing, expected in cases:
            work = runner.evidence / f"control-divergence-{index}-{len(results)}"
            work.mkdir(exist_ok=True)
            if mutate is None:
                copy_corpus(corpus, work)
            else:
                apply_control(corpus, work, d["corpus"], checker.mutate_selected(d["corpus"], mutate))
            listing = checker.divergences
            if not keep_listing:
                listing = work / "divergences-without.json"
                write_json(listing, [e for e in divergences if e is not d])
            code, output = checker.run(f"control-divergence-{index}-{len(results)}", work, [d["corpus"]],
                                       divergences=listing)
            require(code == 1 and expected in output,
                    f"divergence control '{label}' for {d['corpus']} `{d['records']}` was not rejected")
            results.append({"control": f"known divergence {d['corpus']} `{d['records']}`: {label}",
                            "corpus": d["corpus"], "exit_code": code, "expected": expected})
            _compact_control(runner, work)
    return results


def run_controls(runner: Runner, checker: Checker, corpus: Path, only: list[str] | None,
                 divergences: list[dict] | None = None) -> list[dict]:
    """Each mutation must make the checker fail. The value controls apply to the codec corpora
    that are checked; the structural ones to every checked corpus."""
    _control_baseline(runner, corpus)
    checked = set(only) if only else {p.stem for p in corpus.glob("*.json")}
    if checker.selection is not None:
        checked -= set(checker.selection.get("omitted_corpora", []))
    plan = selected_fixed_controls(checker, corpus, checked)
    for name in sorted(checked):
        plan.append((f"unregistered function in {name}", name, _mutate_function, "no registered checker"))
        plan.append((f"checker without records in {name}", name, _mutate_drop_function, "no records for"))
    results = []
    patterns = {}
    for d in divergences or []:
        patterns.setdefault(d["corpus"], []).append(d["records"])
    for name in sorted(checked):
        records = checker.records(name, json.loads((corpus / f"{name}.json").read_text())["records"])
        skip = unobserved_kinds(name)
        for index, (kind, label, present, mutate) in enumerate(KIND_CONTROLS):
            if kind in skip:
                continue
            targets = kind_targets(records, present, patterns.get(name, []))
            if not targets:
                continue
            work = runner.evidence / f"control-kind-{name}-{index}"
            work.mkdir(exist_ok=True)
            def mutate_all(rs, targets=set(targets), mutate=mutate):
                for r in rs:
                    if r["id"] in targets:
                        mutate(r)
            apply_control(corpus, work, name, mutate_all)
            code, output = checker.run(f"control-kind-{name}-{index}", work, [name])
            missed = [t for t in targets
                      if f"MISMATCH {name}/{t} " not in output and f"FAIL {name}/{t}:" not in output]
            require(code == 1 and not missed,
                    f"{label} control in {name}: mutations of {len(missed)} of {len(targets)} records were "
                    f"admitted, e.g. {missed[:3]}")
            results.append({"control": f"{label} in {name}", "corpus": name, "exit_code": code,
                            "records": len(targets)})
            _compact_control(runner, work)
        if "input" not in skip:
            result = _spare_after_nonzero_control(runner, checker, corpus, name, records, patterns.get(name, []))
            if result is not None:
                results.append(result)
    results += _semantic_controls(runner, checker, corpus, checked, patterns)
    def structural_control(indexed):
        index, (label, corpus_name, mutate, expected) = indexed
        work = runner.evidence / f"control-{index}"
        work.mkdir(exist_ok=True)
        apply_control(corpus, work, corpus_name, checker.mutate_selected(corpus_name, mutate))
        code, output = checker.run(f"control-{index}", work, only)
        require(code == 1 and expected in output, f"negative control '{label}' was not rejected")
        _compact_control(runner, work)
        return {"control": label, "corpus": corpus_name, "exit_code": code, "expected": expected}

    # Each full-corpus mutation owns its files and runs the already compiled checker.
    # Interpreted family selections stay serial to avoid concurrent Lake builds.
    workers = runner.control_jobs if getattr(checker, "families", None) is None else 1
    if workers == 1:
        results += [structural_control(item) for item in enumerate(plan)]
    else:
        pool = ThreadPoolExecutor(max_workers=workers)
        try:
            results += list(pool.map(structural_control, enumerate(plan)))
        finally:
            pool.shutdown(wait=True, cancel_futures=True)
    results += _divergence_controls(runner, checker, corpus, divergences or [])
    for index, control in enumerate(c for c in load_family_controls() if c["corpus"] in checked):
        if checker.selection is not None:
            rid = getattr(control["mutate"], "record_id", None)
            require(rid is not None,
                    f"selected replay needs an explicit record_id for family control {control['label']}")
            if rid not in checker.selection["corpora"][control["corpus"]]["selected_ids"]:
                checker.omitted_controls.append({"family": control["family"], "label": control["label"],
                                                  "corpus": control["corpus"], "record": rid})
                continue
        work = runner.evidence / f"control-family-{index}"
        work.mkdir(exist_ok=True)
        apply_control(corpus, work, control["corpus"], control["mutate"])
        code, output = checker.run(f"control-family-{index}", work, [control["corpus"]])
        require(code == 1 and control["expected"] in output,
                f"family control '{control['label']}' ({control['family']}) was not rejected")
        if is_precondition_control(control):
            report = record_report(output, control["corpus"], control["mutate"].record_id)
            require(control["expected"] in report,
                    f"precondition control '{control['label']}' ({control['family']}): the report of its record "
                    f"does not contain {control['expected']!r}")
        results.append({"control": f"{control['family']}: {control['label']}", "corpus": control["corpus"],
                        "exit_code": code, "expected": control["expected"]})
        _compact_control(runner, work)
    if only is None:
        extra = runner.evidence / "control-unregistered"
        extra.mkdir(exist_ok=True)
        copy_corpus(corpus, extra)
        (extra / "unregistered_0_0_0.json").write_text("{}")
        if checker.selection is not None and checker.selection.get("complete"):
            try:
                checker.run("control-unregistered", extra, None)
            except ValueError as error:
                message = str(error)
                require("without registered checkers or authenticated omissions: ['unregistered_0_0_0']" in message,
                        f"unregistered corpus control failed for another reason: {message}")
                results.append({"control": "unregistered corpus file", "validator": "authenticated file set",
                                "error": message})
            else:
                raise ValueError("an unregistered corpus file was accepted")
        else:
            code, output = checker.run("control-unregistered", extra, None)
            require(code == 1 and "without registered checkers" in output, "an unregistered corpus file was accepted")
            results.append({"control": "unregistered corpus file", "exit_code": code})
        _compact_control(runner, extra)
    return results


def model_only(args: argparse.Namespace) -> None:
    evidence = args.evidence_dir.resolve()
    runner = Runner(evidence, args.timeout, getattr(args, "control_jobs", 1))
    selective = bool(args.family or args.corpus)
    if selective:
        families = args.family or families_for(set(args.corpus))
        require(families, f"no family module registers {args.corpus}")
        for f in families:
            require((FAMILIES / f"{f}.lean").exists(), f"no family module SolanalibTest/Conformance/Library/Families/{f}.lean")
    else:
        families = None
        require(generate_registry(write=False) and readme_tables_current(),
                "SolanalibTest/Conformance/Library/Registry.lean or a generated REFERENCE.md table (known divergences, "
                "not tested, open preconditions) is stale; run run.py --generate-registry")
    _, version = runner.run("lean-version", ["lake", "env", "lean", "--version"], REPO)
    require(LEAN.rpartition(":v")[2] in version, f"unexpected Lean version: {version.strip()}")
    checker = Checker(runner, families)
    checker.build()
    only = args.corpus or None
    descriptors = None
    if getattr(args, "registered_checkers", False):
        code, listing = checker.run("checker-keys", CORPUS, only, describe=True, divergences=False)
        lines = [line.removeprefix("CHECKERS\t") for line in listing.splitlines()
                 if line.startswith("CHECKERS\t")]
        require(code == 0 and len(lines) == 1, "missing or ambiguous compiled checker key report")
        descriptors = json.loads(lines[0])
        require(isinstance(descriptors, list), "malformed compiled checker key report")
        if only is None:
            only = sorted({row["corpus"] for row in descriptors})
    if selective and only is None:
        # --family without --corpus: every corpus the selected families register.
        _, listing = checker.run("list", CORPUS, None, registered=True, divergences=False)
        only = sorted(parse_counts(listing))
    auth = authenticate(only=set(only) if selective else None)
    write_json(evidence / "corpus-authentication.json",
               {"corpora": {k: {"records": v["records"], "crates": v["crates"]} for k, v in auth["summaries"].items()},
                "drivers": {d: {"recorded_utc": m["recorded_utc"], "rust": m["rust"]} for d, m in auth["manifests"].items()}})
    if descriptors is not None:
        checker.selection = checker_selection.prepare(CORPUS, auth, descriptors, set(only), complete=not selective)
        write_json(evidence / "checker-selection.json", checker.selection)
    divergences = load_divergences(set(only) if selective else None)
    if checker.selection is not None:
        divergences = [d for d in divergences if any(glob_match(d["records"], rid)
                       for rid in checker.selection["corpora"].get(d["corpus"], {}).get("selected_ids", []))]
    checker.divergences = evidence / "divergences.json"
    write_json(checker.divergences, divergences)
    checker.spare_writes = evidence / "spare-writes.json"
    write_json(checker.spare_writes, spare_writers())
    code, output = checker.run("check", CORPUS, only if selective else None)
    require(code == 0, f"the models rejected recorded behavior; see {evidence / 'run-check.log'}")
    counts = parse_counts(output)
    write_json(evidence / "counts.json", counts)
    check_counts(counts, auth["summaries"] if checker.selection is None
                 else checker.selection["selected_summaries"])
    if checker.selection is not None:
        checker_selection.check_omissions(output, checker.selection)
    audit = evidence / "Audit.lean"
    audited = families if families is not None else family_modules()
    models = source_map()
    theorems = [t for t in load_requires_theorems(models=models) if t["detail"] in audited]
    # Executable roots are buildable but intentionally not importable Lake libraries.
    # Elaborate the exact entry-point source beside the imported checker environment.
    entrypoint = ROOT / "SolanalibTest/Conformance/LibraryMain.lean" if families is None else checker.driver
    audit.write_text(AUDIT.replace("{imports}", checker.audit_imports())
                     .replace("{entrypoint}", entrypoint.read_text())
                     + decides_audit_source(audited, models, [t["theorem"] for t in theorems]))
    _, audit_output = runner.run("axioms", lean_command(audit), REPO)
    write_json(evidence / "axioms.json", checked_axioms(audit_output))
    checked = set(only) if selective else {p.stem for p in CORPUS.glob("*.json")}
    if checker.selection is not None:
        checked -= set(checker.selection["omitted_corpora"])
    decides = checked_decides(audit_output, models, load_not_tested(models=models), complete=families is None,
                              requires_open=load_requires_open(models=models),
                              cross_function=load_cross_function(models=models), requires_theorems=theorems,
                              precondition_controls=precondition_control_index(checked),
                              corpora=checked if selective else None)
    write_json(evidence / "decides.json", decides)
    controls = decides["controls"] + run_controls(runner, checker, CORPUS, only if selective else None, divergences)
    write_json(evidence / "controls.json", controls)
    if checker.selection is not None:
        write_json(evidence / "selection-omitted-controls.json", checker.omitted_controls)
        if checker.selection["complete"]:
            checker_selection.check_corpus_files(CORPUS, checker.selection)
    total = sum(t["total"] for fs in counts.values() for t in fs.values())
    divergent = sum(t["divergent"] for fs in counts.values() for t in fs.values())
    functions = sum(len(fs) for fs in counts.values())
    write_json(evidence / "run-status.json", {
        "status": "passed", "records": total, "known_divergences": divergent,
        "checkers": functions, "controls": len(controls),
        "control_jobs": runner.control_jobs if families is None else 1,
        "families": families, "corpora": sorted(counts),
        **({"selection": "registered checker keys", "omitted_records": len(checker.selection["omissions"]),
            "omitted_corpora": checker.selection["omitted_corpora"],
            "whole_corpus_omitted_records": sum(checker.selection["corpora"][name]["omitted_records"]
                                                for name in checker.selection["omitted_corpora"]),
            "omitted_controls": len(checker.omitted_controls)} if checker.selection is not None else {}),
        "finished_utc": datetime.now(timezone.utc).isoformat()})
    print(f"Passed: {total} records ({divergent} known divergences rejected as listed), "
          f"{functions} function instantiations, {len(controls)} negative controls; "
          f"evidence: {evidence}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--record", action="store_true", help="run Rust drivers and write their corpus files")
    mode.add_argument("--model-only", action="store_true", help="check the committed corpus with Lean")
    mode.add_argument("--generate-registry", action="store_true", help="rewrite SolanalibTest/Conformance/Library/Registry.lean")
    mode.add_argument("--check-registry", action="store_true", help="fail if Registry.lean is stale")
    parser.add_argument("--evidence-dir", type=Path)
    parser.add_argument("--driver", action="append", help="record only this driver (repeatable)")
    parser.add_argument("--family", action="append", help="check only this family module (repeatable)")
    parser.add_argument("--corpus", action="append", help="check only this corpus (repeatable)")
    parser.add_argument("--registered-checkers", action="store_true",
                        help="check authenticated corpora, permitting only exact reviewed record omissions")
    parser.add_argument("--target-dir", type=Path, help="Cargo target root, one shared subdirectory per workspace")
    parser.add_argument("--offline", action="store_true", help="pass --offline to cargo")
    parser.add_argument("--twice", action="store_true", help="record each driver twice and require equal bytes")
    parser.add_argument("--no-write-corpus", dest="write_corpus", action="store_false",
                        help="record into the evidence directory only")
    parser.add_argument("--timeout", type=int, default=1800, help="maximum seconds per subprocess")
    parser.add_argument("--control-jobs", type=int, default=1,
                        help="parallel full-corpus mutation checks with the compiled runner (default: 1)")
    args = parser.parse_args()
    if args.control_jobs < 1:
        parser.error("--control-jobs must be positive")
    if args.registered_checkers and not args.model_only:
        parser.error("--registered-checkers is available only with --model-only")
    if args.control_jobs != 1 and not args.model_only:
        parser.error("--control-jobs is available only with --model-only")
    if args.generate_registry or args.check_registry:
        current = generate_registry(write=args.generate_registry)
        table = readme_tables_current(write=args.generate_registry)
        if args.check_registry and not (current and table):
            print("SolanalibTest/Conformance/Library/Registry.lean or a generated REFERENCE.md table (known divergences, "
                  "not tested, open preconditions) is stale; run run.py --generate-registry", file=sys.stderr)
            return 1
        return 0
    if args.evidence_dir is None:
        parser.error("--evidence-dir is required with --record and --model-only")
    baseline = args.evidence_dir / "control-baseline"
    if args.model_only and (baseline.exists() or baseline.is_symlink()):
        parser.error("saved control baseline already exists; use a fresh --evidence-dir")
    args.evidence_dir.mkdir(parents=True, exist_ok=True)
    write_json(args.evidence_dir / "run-status.json",
               {"status": "running", "started_utc": datetime.now(timezone.utc).isoformat()})
    try:
        record(args) if args.record else model_only(args)
    except Exception as error:
        write_json(args.evidence_dir / "run-status.json",
                   {"status": "failed", "error": str(error), "finished_utc": datetime.now(timezone.utc).isoformat()})
        print(f"solana-library-conformance: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
