"""Record unmodified Solana library functions natively and check the Lean models against them.

    run.py --record --evidence-dir DIR [--driver D ...]
        build the selected Rust drivers (default: all rust/*/driver.toml) at their pinned versions,
        run them, and replace their corpus files and corpus/manifests/<driver>.json
    run.py --model-only --evidence-dir DIR [--family F ...] [--corpus C ...]
        check the corpus against its manifests, build the Lean checker, decide every record,
        audit the axioms and run the negative controls (no Rust needed). With --family/--corpus only the corpora of the selected families are checked, through the Lean interpreter, so the modules of the other families need not build.
    run.py --generate-registry    rewrite SolanalibTest/Conformance/Library/Registry.lean from the family modules
    run.py --check-registry       fail if SolanalibTest/Conformance/Library/Registry.lean is stale

The model-only check needs Python 3.12 and the Lean toolchain of the root package. Recording also needs the Rust toolchain of the
suite (rust-toolchain.toml). Modeled dependencies have exact constraints; incidental packages resolve afresh.
"""

