# Drivers are discovered from rust/<name>/driver.toml and grouped in compatible Cargo workspaces.
# Each driver lists the corpus files it writes:
#
#     corpora = ["solana_account_view_1_0_0"]       # corpus/<name>.json, unique across drivers
#     inputs = ["rust/common/borsh_de.rs"]           # optional: extra files it includes (#[path])
#     unobserved = ["syscalls"]                      # optional: record kinds its models do not observe
#     host = true                                    # optional: records the host branch (no Solana cfg)
#     spare_writes = ["solana_account_view::AccountView::close"]   # optional: functions (globs over the
#                                                    # the `function` of the record) whose calls may change spare bytes
#     region = "none"                                # optional: its accounts are built as values, with no
#                                                    # loader region (no read-back region or frame to compare)
#     scope = "whole-signature-mock"                 # optional: requires an executable configuration probe
#     [build_probe]
#     argument = "--build-config"
#     profile = "dev"                                # passed explicitly to Cargo for this driver
#     panic = "abort"                                # checked against the cfg!(panic) of the executable
#
# The runner requires every read-back region byte no model represents to be unchanged by a call (the
# count word, padding, alignment padding, rent epoch, spare bytes, instruction data and program id);
# `spare_writes` exempts the spare bytes of the listed functions, whose family models represent them.
#
# The inputs of a driver are its own files, those of its path dependencies (recorder, shim, ...) and the
# listed extra files; a change to any of them requires a fresh recording of that driver.


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def write_json(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def discover_drivers(root: Path = ROOT) -> dict[str, dict]:
    drivers, owner = {}, {}
    for spec_path in sorted((root / "rust").glob("*/driver.toml")):
        name = spec_path.parent.name
        spec = tomllib.loads(spec_path.read_text())
        corpora = spec.get("corpora")
        require(isinstance(corpora, list) and corpora and all(isinstance(c, str) for c in corpora),
                f"{spec_path}: `corpora` must list the corpus files the driver writes")
        for c in corpora:
            require(CORPUS_NAME.match(c) is not None, f"{spec_path}: corpus name {c!r} must match {CORPUS_NAME.pattern}")
            require(c not in owner, f"corpus {c} is written by both {owner.get(c)} and {name}")
            owner[c] = name
        extra = spec.get("inputs", [])
        require(isinstance(extra, list) and all(isinstance(x, str) for x in extra), f"{spec_path}: bad `inputs`")
        unobserved = spec.get("unobserved", [])
        require(isinstance(unobserved, list) and set(unobserved) <= {"syscalls", "input", "terminated"},
                f"{spec_path}: `unobserved` lists record kinds among syscalls, input, terminated")
        host = spec.get("host", False)
        require(isinstance(host, bool), f"{spec_path}: `host` is true or false")
        region = spec.get("region")
        require(region in (None, "none"), f"{spec_path}: `region` is \"none\" (the driver builds no loader region) or absent")
        spare_writes = spec.get("spare_writes", [])
        require(isinstance(spare_writes, list) and all(isinstance(f, str) and f for f in spare_writes),
                f"{spec_path}: `spare_writes` lists function globs")
        profile = spec.get('profile', 'dev')
        require(profile in native_dependencies.PROFILES, f'{spec_path}: unknown recording profile')
        probe = build_probe.configuration(spec, spec_path)
        require(probe is None or probe['profile'] == profile, f'{spec_path}: probe and recording profiles differ')
        drivers[name] = {"corpora": corpora, "inputs": extra, "unobserved": unobserved, "host": host,
                         "spare_writes": spare_writes, "regionless": region == "none",
                         "profile": profile, "build_probe": probe}
    return drivers


def _package_files(directory: Path, driver: bool) -> list[Path]:
    """Package sources and driver configuration, excluding temporary Cargo resolutions."""
    files = [directory / "Cargo.toml"]
    for optional in ("build.rs",) + (((".cargo/config.toml", "driver.toml")) if driver else ()):
        if (directory / optional).exists():
            files.append(directory / optional)
    return files + sorted((directory / "src").rglob("*.rs"))


def _path_dependencies(directory: Path) -> list[Path]:
    manifest = tomllib.loads((directory / "Cargo.toml").read_text())
    deps = []
    for table in ("dependencies", "dev-dependencies", "build-dependencies"):
        for spec in manifest.get(table, {}).values():
            if isinstance(spec, dict) and "path" in spec:
                deps.append((directory / spec["path"]).resolve())
    return deps


INCLUDE = re.compile(r'#\[path\s*=\s*"([^"]+)"\]|\binclude(?:_str|_bytes)?!\s*\(\s*"([^"]+)"\s*\)')


def driver_inputs(name: str, root: Path = ROOT, drivers: dict | None = None) -> list[str]:
    drivers = drivers if drivers is not None else discover_drivers(root)
    seen: list[Path] = []
    pending = [(root / "rust" / name).resolve()]
    while pending:
        directory = pending.pop()
        if directory in seen:
            continue
        seen.append(directory)
        pending.extend(_path_dependencies(directory))
    files = [f for i, d in enumerate(seen) for f in _package_files(d, driver=i == 0)]
    workspace = native_dependencies.workspace(root / 'rust' / name)
    files += [workspace / 'Cargo.toml', root / 'native-pins.toml']
    # Every member manifest constrains workspace resolution, including the manifests
    # of its path dependencies. Only the selected driver needs the other source bytes.
    pending = [(workspace / member).resolve()
               for member in native_dependencies.read_cargo(workspace)['workspace']['members']]
    manifests = set()
    while pending:
        directory = pending.pop()
        if directory in manifests:
            continue
        manifests.add(directory)
        files.append(directory / 'Cargo.toml')
        pending.extend(_path_dependencies(directory))
    rel = sorted({str(f.resolve().relative_to(root.resolve())) for f in files} | set(drivers[name]["inputs"]))
    # Sources a hashed file includes (`#[path = ...]`, `include!`, `include_str!`, `include_bytes!`) must be
    # hashed too: listed in the `inputs` of the driver unless they are already package sources.
    for r in rel:
        if not r.endswith(".rs") or not (root / r).exists():
            continue
        text = (root / r).read_text()
        for groups in INCLUDE.findall(text):
            target = next(g for g in groups if g)
            included = str(((root / r).parent / target).resolve().relative_to(root.resolve()))
            require(included in rel, f"driver {name}: {r} includes {target} ({included}), which is not a hashed "
                                     "input; list it in the `inputs` of the driver")
    return rel


def input_hashes(name: str, root: Path = ROOT, drivers: dict | None = None) -> dict[str, str]:
    return {rel: sha256(root / rel) for rel in driver_inputs(name, root, drivers)}


def toolchain_problem(rustc_lines: list[str], channel: str) -> str | None:
    """Why `rustc -vV` output does not belong to the pinned nightly channel, or None. A nightly named
    `nightly-YYYY-MM-DD` is built from a commit of that day or up to three days before."""
    from datetime import date
    info = dict(line.split(": ", 1) for line in rustc_lines if ": " in line)
    match = re.fullmatch(r"nightly-(\d{4})-(\d{2})-(\d{2})", channel)
    if match is None:
        return f"the pinned channel {channel} is not a dated nightly"
    if "nightly" not in info.get("release", ""):
        return f"rustc release {info.get('release')!r} is not a nightly"
    try:
        commit = date.fromisoformat(info.get("commit-date", ""))
    except ValueError:
        return "rustc -vV gives no commit-date"
    if not re.fullmatch(r"[0-9a-f]{40}", info.get("commit-hash", "")):
        return "rustc -vV gives no commit-hash"
    days = (date(*map(int, match.groups())) - commit).days
    if not 0 <= days <= 3:
        return f"rustc commit-date {commit} does not belong to {channel}"
    return None


def toolchain_overrides(root: Path = ROOT) -> list[str]:
    """`rust-toolchain` files under rust/: forbidden, the drivers build with the toolchain of the suite."""
    return sorted(str(f.relative_to(root)) for f in (root / "rust").rglob("rust-toolchain*"))


def registry_pins() -> dict[str, set[str]]:
    """Crate versions pinned by packages/solanalib-specs/source-map (`packages` keys `<name>-<version>`)."""
    pins: dict[str, set[str]] = {}
    for path in sorted((REPO / "packages/solanalib-specs/source-map").glob("*.json")):
        for key in json.loads(path.read_text()).get("packages", {}):
            match = re.fullmatch(r"(.+?)-(\d+\.\d+\.\d+.*)", key)
            if match:
                pins.setdefault(match[1], set()).add(match[2])
    return pins


