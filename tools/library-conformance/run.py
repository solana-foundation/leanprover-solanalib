# Known divergences
# ---------------------------------------------------------------------------
#
# divergences/<corpus>.toml, owned by the family of the corpus:
#
#     [[divergence]]
#     records = "with_values/*/left_drop_panics"   # glob over record ids (`*` matches any text)
#     model = "Solanalib.Specs.AnchorLang.error.Error.with_values_run"   # the reference of the checker, exactly
#     reason = "rustc leaks the moved receiver when an operand destructor panics"
#     link = "https://github.com/rust-lang/rust/issues/47949"   # upstream issue or evidence
#
# The checker requires the model to REJECT every listed record; a listed record that is admitted,
# a listing that matches no record or names another model, and every unlisted mismatch fail the run.


def glob_match(pattern: str, text: str) -> bool:
    return re.fullmatch(".*".join(re.escape(part) for part in pattern.split("*")), text, re.S) is not None


def load_divergences(corpora: set[str] | None = None, directory: Path = DIVERGENCES) -> list[dict]:
    entries = []
    for path in sorted(directory.glob("*.toml")):
        if corpora is not None and path.stem not in corpora:
            continue
        spec = tomllib.loads(path.read_text())
        require(set(spec) <= {"divergence"}, f"{path}: only [[divergence]] tables are allowed")
        items = spec.get("divergence", [])
        require(isinstance(items, list) and items, f"{path}: no [[divergence]] entries")
        for item in items:
            require(set(item) <= {"records", "model", "reason", "link", "exit", "reason_contains"}
                    and {"records", "model", "reason"} <= set(item)
                    and all(isinstance(v, str) and v for v in item.values()),
                    f"{path}: each divergence has string `records`, `model`, `reason` and optional `link`, "
                    "`exit`, `reason_contains`")
            require(item.get("exit") in (None, "returned", "unwound", "terminated"),
                    f"{path}: `exit` is returned, unwound or terminated")
            require(not any(c.isspace() for c in item["model"]), f"{path}: `model` contains whitespace")
            entries.append({"corpus": path.stem, **item})
    return entries


def divergence_table(entries: list[dict]) -> str:
    rows = ["| Corpus | Records | Model | Reason | Upstream |", "| --- | --- | --- | --- | --- |"]
    for e in entries:
        link = f"[link]({e['link']})" if e.get("link") else ""
        reason = e["reason"].replace("|", "\\|")
        rows.append(f"| `{e['corpus']}` | `{e['records']}` | `{e['model']}` | {reason} | {link} |")
    if not entries:
        rows.append("| none | | | | |")
    return "\n".join(rows)


def generate_readme_table(begin: str, end: str, table: str, write: bool) -> bool:
    """Check or update a generated table in the detailed reference guide."""
    text = REFERENCE.read_text()
    require(begin in text and end in text, f"{REFERENCE.name} lacks the markers {begin} ... {end}")
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    new = f"{head}{begin}\n{table}\n{end}{tail}"
    current = new == text
    if write and not current:
        REFERENCE.write_text(new)
    return current


def generate_divergence_table(write: bool = True) -> bool:
    """Check or update the known-divergences table of the reference guide."""
    return generate_readme_table(TABLE_BEGIN, TABLE_END, divergence_table(load_divergences()), write)


