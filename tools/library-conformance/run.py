from hexform import COMPACT_HEX, HEX, ZERO_RUN, compact_hex, expand_hex  # noqa: E402,F401


def validate_corpus(path: Path) -> dict:
    """Check the structure of one corpus file; return its summary."""
    data = json.loads(path.read_text())
    require(data.get("schema") == SCHEMA, f"{path.name}: unknown schema")
    require(data.get("corpus") == path.stem, f"{path.name}: corpus name differs from file name")
    crates = data.get("crates")
    require(isinstance(crates, list) and crates and all(set(c) == {"name", "version"} for c in crates),
            f"{path.name}: malformed crates")
    records = data.get("records")
    require(isinstance(records, list) and records, f"{path.name}: no records")
    ids, functions = set(), {}
    for record in records:
        rid = record.get("id")
        require(isinstance(rid, str) and rid and not rid.startswith(path.stem + "/"),
                f"{path.name}: bad id {rid!r}")
        rid = f"{path.stem}/{rid}"
        require(rid not in ids, f"{path.name}: duplicate id {rid}")
        ids.add(rid)
        require(set(record) <= {"id", "function", "generics", "layout", "state", "args", "outcome", "observed"}
                and {"function", "generics", "state", "args", "outcome"} <= set(record),
                f"{rid}: unexpected or missing fields")
        require(isinstance(record["generics"], dict)
                and all(isinstance(v, str) for v in record["generics"].values()), f"{rid}: bad generics")
        outcome = record["outcome"]
        require(outcome.get("exit") in EXITS, f"{rid}: unknown exit {outcome.get('exit')!r}")
        if outcome["exit"] != "terminated":
            require("state" in outcome, f"{rid}: outcome without state")
        if outcome["exit"] == "returned":
            require("result" in outcome, f"{rid}: returned without result")
        for value in _strings(record):
            if value.startswith("0x"):
                raise ValueError(f"{rid}: hex strings carry no prefix")
            if "[" in value and COMPACT_HEX.match(value):
                require(compact_hex(expand_hex(value)) == value, f"{rid}: non-canonical zero run in {value[:60]!r}")
            elif HEX.match(value) and len(value) >= 2 * ZERO_RUN and "00" * ZERO_RUN in value:
                require(compact_hex(bytes.fromhex(value)) == value, f"{rid}: a run of 64+ zero bytes is not compacted")
        key = record["function"] + " [" + ", ".join(f"{k} = {v}" for k, v in record["generics"].items()) + "]"
        functions[key] = functions.get(key, 0) + 1
    return {"records": len(records), "crates": crates, "functions": dict(sorted(functions.items()))}


def _strings(value: object):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for v in value.values():
            yield from _strings(v)
    elif isinstance(value, list):
        for v in value:
            yield from _strings(v)


def authenticate(corpus: Path = CORPUS, root: Path = ROOT, only: set[str] | None = None) -> dict:
    """Check the corpus and the current driver inputs against the committed per-driver manifests.

    This is consistency with supplied hashes, not an independent native re-recording: coordinated
    edits to a record and its manifest can pass. `only`: check just the drivers that write these
    corpora (per-family runs); otherwise every registered driver (rust/*/driver.toml) must have a
    manifest, no manifest may belong to an unknown driver, and every corpus file must belong to a
    driver."""
    drivers = discover_drivers(root)
    owner = {c: d for d, spec in drivers.items() for c in spec["corpora"]}
    if only is None:
        selected = sorted(drivers)
        present = {p.stem for p in corpus.glob("*.json")}
        require(present == set(owner),
                f"corpus files without a driver: {sorted(present - set(owner))}; "
                f"driver corpora without a file: {sorted(set(owner) - present)}")
        recorded = {p.stem for p in (corpus / "manifests").glob("*.json")}
        require(recorded == set(drivers),
                f"manifest driver set differs from the registered drivers: without a manifest "
                f"{sorted(set(drivers) - recorded)}, unknown {sorted(recorded - set(drivers))}")
    else:
        unknown = only - set(owner)
        require(not unknown, f"no driver writes the corpora {sorted(unknown)}")
        selected = sorted({owner[c] for c in only})
    toolchain = tomllib.loads((ROOT / "rust-toolchain.toml").read_text())["toolchain"]["channel"]
    overrides = toolchain_overrides(root)
    require(not overrides, f"toolchain overrides under rust/ are not allowed: {overrides}")
    pins = registry_pins()
    summaries, manifests = {}, {}
    for driver in selected:
        path = corpus / "manifests" / f"{driver}.json"
        require(path.exists(), f"manifest driver set differs from the registered drivers: driver {driver} "
                f"has no manifest; run with --record --driver {driver}")
        manifest = json.loads(path.read_text())
        manifests[driver] = manifest
        require(manifest.get("schema") == MANIFEST_SCHEMA and manifest.get("driver") == driver,
                f"{path}: unknown schema or driver")
        require(sorted(manifest["corpora"]) == sorted(f"{c}.json" for c in drivers[driver]["corpora"]),
                f"driver {driver}: corpus assignment differs from the registered driver (driver.toml); "
                "run with --record")
        require(manifest.get("rust", {}).get("toolchain") == toolchain,
                f"driver {driver} recorded with {manifest.get('rust', {}).get('toolchain')}, "
                f"repository toolchain is {toolchain}; run with --record")
        problem = toolchain_problem(manifest.get("rust", {}).get("rustc", []), toolchain)
        require(problem is None, f"driver {driver}: the recorded rustc does not match the pinned toolchain: {problem}")
        build_probe.authenticate(manifest, drivers[driver]["build_probe"], drivers[driver]["host"], driver)
        require(input_hashes(driver, root, drivers) == manifest["inputs"],
                f"driver {driver}: inputs changed since the recording; run with --record --driver {driver}")
        directory = root / "rust" / driver
        resolution = manifest.get('resolution')
        native_dependencies.validate_resolution(directory, resolution, native_dependencies.reviewed_checksums())
        expected_profile = native_dependencies.profile(directory, drivers[driver]['profile'])
        require(all(manifest['rust'].get(key) == value for key, value in expected_profile.items()),
                f'{driver}: recorded compiler profile differs from the workspace profile')
        for name, entry in manifest["corpora"].items():
            file = corpus / name
            require(file.exists(), f"{name}: missing corpus file")
            require(sha256(file) == entry["sha256"], f"{name}: hash differs from the recorded corpus")
            summary = validate_corpus(file)
            require(summary["records"] == entry["records"], f"{name}: record count differs")
            for crate in summary["crates"]:
                linked = native_dependencies.selected_version(directory, resolution, crate["name"])
                require(linked == crate["version"],
                        f"{name}: {crate['name']} {crate['version']} is not the version {driver} links "
                        f"({linked or 'none or ambiguous'})")
                versions = pins.get(crate["name"])
                require(versions is None or crate["version"] in versions,
                        f"{name}: {crate['name']} {crate['version']} is not a registry pin ({sorted(versions or [])})")
            summaries[name] = summary
    return {"manifests": manifests, "summaries": summaries}


